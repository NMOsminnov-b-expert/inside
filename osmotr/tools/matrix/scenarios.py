def unit_tests():
    out = set()
    for base in ('shared/src/jvmTest/kotlin', 'app/src/test/kotlin'):
        for dp, _, fs in os.walk(os.path.join(ROOT, base)):
            for f in fs:
                if f.endswith('.kt'):
                    cls = f[:-3]
                    src = open(os.path.join(dp, f), encoding='utf-8').read()
                    for m in re.finditer(r'@Test\s+fun\s+([^\s(]+)', src):
                        out.add('%s.%s' % (cls, m.group(1)))
    return out


def paths():
    src = open(os.path.join(ROOT, 'tools', 'matrix', 'paths.py'), encoding='utf-8').read()
    m = re.search(r'PATHS = \{(.*?)\n\}', src, re.S)
    return set(re.findall(r"'([^']+)':", m.group(1)))


def main():
    units, ps = unit_tests(), paths()
    bad, empty = [], []
    for sid, what, refs in S:
        if not refs:
            empty.append(sid)
        for r in refs:
            kind, _, name = r.partition(':')
            if (kind == 'unit' and name not in units) or (kind == 'path' and name not in ps) or kind not in ('unit', 'path'):
                bad.append((sid, r))
    if '--list' in sys.argv:
        for sid, what, refs in S:
            print('%-22s %s' % (sid, what))
            for r in refs:
                print('    %s%s' % (r, '   ← НЕТ ТАКОГО' if (sid, r) in bad else ''))
    used_paths = {r[5:] for _, _, refs in S for r in refs if r.startswith('path:')}
    for p in sorted(ps - used_paths):
        print('путь матрицы ни к одному сценарию не привязан: %s' % p)
    for sid in empty:
        print('сценарий без теста: %s' % sid)
    for sid, r in bad:
        print('нет теста: %s → %s' % (sid, r))
    print('сценариев %d, ссылок %d, битых %d' % (len(S), sum(len(x[2]) for x in S), len(bad)))
    # ТЗ ссылается на сценарии реестра (столбец «Реестр»): неизвестный — ТЗ и проверки разошлись.
    ids = {sid for sid, _, _ in S}
    tz = open(os.path.join(ROOT, 'docs', 'ТЗ.md'), encoding='utf-8').read()
    tz_refs = {r for row in re.findall(r'^\|.*\|\s*(`[^|]+)\|\s*$', tz, re.M) for r in re.findall(r'`([^`]+)`', row)}
    unknown = sorted(tz_refs - ids)
    for r in unknown:
        print('ТЗ ссылается на сценарий, которого нет в реестре: %s' % r)
    # Путь без сценария — ошибка: иначе он выпадает из учёта, а проверка «зелёная» (так лежали три пути объекта).
    loose = ps - used_paths
    return 1 if bad or empty or loose or unknown else 0


if __name__ == '__main__':
    sys.exit(main())
