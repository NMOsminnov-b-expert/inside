const root = new URL('../..', import.meta.url).pathname
const matrix = readFileSync(root + 'tools/web/matrix.mjs', 'utf8')
const paths = new Set([...matrix.matchAll(/^ {2}async '([^']+)'\(r\)/gm)].map(m => m[1]))
const units = new Set()
for (const f of ['XlsTest', 'TemplatesTest', 'DirtyDataTest', 'InventoryTest', 'ReportColumnsTest', 'JournalTest', 'VideoTest']) {
  try { for (const m of readFileSync(`${root}shared/src/jvmTest/kotlin/kg/osmotr/core/${f}.kt`, 'utf8').matchAll(/@Test\s+fun\s+`?([^\s(`]+)/g)) units.add(`${f}.${m[1]}`) } catch {}
}
const bad = [], noWeb = []
for (const [id, , refs] of S) {
  if (!refs.some(r => r.startsWith('web:') || r.startsWith('нет:'))) noWeb.push(id)
  for (const r of refs) {
    const [kind, ...rest] = r.split(':'); const name = rest.join(':')
    if ((kind === 'web' && !paths.has(name)) || (kind === 'unit' && !units.has(name))) bad.push([id, r])
  }
}
if (process.argv.includes('--list')) for (const [id, what, refs] of S) {
  console.log(`${id.padEnd(22)} ${what}`)
  for (const r of refs) console.log(`    ${r}${bad.some(b => b[0] === id && b[1] === r) ? '   ← НЕТ ТАКОГО' : ''}`)
}
const used = new Set(S.flatMap(s => s[2]).filter(r => r.startsWith('web:')).map(r => r.slice(4)))
for (const p of paths) if (!used.has(p)) console.log(`путь матрицы ни к одному сценарию не привязан: ${p}`)
for (const id of noWeb) console.log(`сценарий без пути PWA: ${id}`)
for (const [id, r] of bad) console.log(`нет теста: ${id} → ${r}`)
console.log(`сценариев ${S.length}, неприменимо в браузере ${S.filter(s => s[2].some(r => r.startsWith('нет:'))).length}, битых ссылок ${bad.length}`)
process.exit(bad.length || noWeb.length ? 1 : 0)
