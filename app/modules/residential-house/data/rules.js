// Правила состава ОЦ «Жилое здание (дом)».
//
// Недвижимость: в объект оценки любого типа можно добавить любой недвижимый ОИ
// — участок, квартиру, жилой дом, гражданское, производственное или прочее
// строение (решение пользователя 02.09.2026). Ограничений по типу ОЦ нет:
// какой ОИ реально стоит на объекте, знает только оценщик.
//
// card — идентификатор карточки ОИ внутри ЭТОГО модуля (см. oi/registry.js);
// residential помечает жилое строение, catClass — класс ОИ по умолчанию.
export const OI_TYPES = [
  { label: 'Земельный участок', card: 'land' },
  { label: 'Квартира', card: 'apartment' },
  // Строения — как в нежилом здании (дверь civil/card.js, BUILDING_OI_TYPES):
  // одно «Здание», вид литеры указывают внутри по фото (решение пользователя
  // 23.09.2026), «Прочее строение» заводится сразу прочим. Распространено
  // 13.10.2026; прежде здесь были «Гражданское здание» и «Производственное
  // строение».
  { label: 'Здание', card: 'building' },
  { label: 'Жилой дом', card: 'building', residential: true },
  { label: 'Прочее строение', card: 'building', litKind: 'other' },
  // Вспомогательная постройка — как в нежилом здании (civil/card.js,
  // распространение 13.10.2026): своя таблица под перечнем, правка в ячейках.
  { label: 'Вспомогательная постройка', card: 'aux' },
];

export const MOVABLE_OI_TYPES = [
  // Один пункт на всё движимое (решение пользователя 07.09.2026, ветка mech):
  // офисная техника ничем не отличается от любого другого оборудования и
  // различается классом в классификаторе карточки, а не отдельным видом ОИ.
  { label: 'Механизмы и оборудование', card: 'mech' },
  // Транспорт вынесен отдельным видом, а не классом внутри механизмов: у ТС
  // свои опознавательные сведения (госномер, VIN, регистрационные документы),
  // и в перечне его ищут по ним.
  { label: 'Транспортное средство', card: 'vehicle' },
];

export function realtyTypes() {
  return OI_TYPES;
}

// Движимое — только у имущественного комплекса, как в гражданском (эталон).
export function movableTypes(rec) {
  return rec && rec.complex ? MOVABLE_OI_TYPES : [];
}

export function oiTypeByLabel(label, rec) {
  return [...OI_TYPES, ...movableTypes(rec)].find((t) => t.label === label) || null;
}
