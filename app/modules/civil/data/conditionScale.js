// Шкала состояния и корректировки по состоянию — методология «Категории и
// классы зданий», разделы «Описание таблицы состояния, физического износа и
// корректировок средней стоимости ремонта» и «Полная матрица корректировок по
// состоянию» (граф: ref:metodologiya-kategorii-klassy-zdaniy).
//
// У каждой градации: ранг (5…1 с шагом 0,5), диапазон физического износа из
// затратного подхода, средний % стоимости ремонта — середина диапазона.
// Корректировка между двумя состояниями:
//     (100 − ср.% ремонта строки) / (100 − ср.% ремонта столбца)
// — во сколько раз скорректировать стоимость объекта в состоянии строки, чтобы
// привести его к состоянию столбца. Матрица зеркальна: значения в симметричных
// ячейках обратны друг другу, на диагонали 1,00.
//
// Недопустимые значения (в методологии — красные): корректировки с участием
// «Требует капитального ремонта» и «Неудовлетворительное» — аналог в таком
// состоянии слишком далёк от объекта и исключается. Пары, где деградация
// заведомо запредельная, методология не рассчитывает вовсе (пустые ячейки) —
// так же и здесь.
//
// Не реализовано: колонка «с внешним износом» — методология показывает её на
// условных 50 % и откладывает механизм до затратного подхода.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: шкала и диапазоны — настройка методики с датой
// действия (как коэффициенты класса в capClass.js): поправка, посчитанная по
// прежней шкале, иначе молча изменится у всех отчётов.
import { BUILD_CONDITION, CONDITION_RANK } from './dictionaries.js';

// [состояние, износ от, износ до, средний % ремонта]
const WEAR = [
  ['Отличное', 0, 5, 2.5],
  ['Отличное / хорошее', 6, 10, 8.0],
  ['Хорошее', 11, 20, 15.5],
  ['Хорошее / удовлетворительное', 21, 30, 25.5],
  ['Удовлетворительное', 31, 40, 35.5],
  ['Удовлетворительное / требует ремонта', 41, 50, 45.5],
  ['Требует ремонта', 51, 60, 55.5],
  ['Требует капитального ремонта', 61, 80, 70.5],
  ['Неудовлетворительное', 81, 100, 90.5],
];

export const CONDITION_SCALE = WEAR.map(([label, from, to, repair]) => ({
  label, rank: CONDITION_RANK[label], wearFrom: from, wearTo: to, repair,
}));

// Порядок шкалы совпадает с перечнем состояния (без «Не выбрано»).
export const SCALE_LABELS = BUILD_CONDITION.filter((x) => CONDITION_RANK[x]);

export const scaleOf = (label) => CONDITION_SCALE.find((s) => s.label === label) || null;

// Короткое описание градации для подсказок: «ранг 4 · физический износ 11–20 %».
export function scaleHint(label) {
  const s = scaleOf(label);
  if (!s) return '';
  return `ранг ${String(s.rank).replace('.', ',')} · износ ${s.wearFrom}–${s.wearTo} %`;
}

// Полное описание — для подсказки при наведении.
export function scaleTitle(label) {
  const s = scaleOf(label);
  if (!s) return '';
  return `Ранг ${String(s.rank).replace('.', ',')}; физический износ из затратного подхода ${s.wearFrom}–${s.wearTo} %; `
    + `средний % стоимости ремонта ${String(s.repair).replace('.', ',')}`;
}

// Градация по проценту физического износа (для объекта, где износ посчитан).
export function scaleByWear(pct) {
  if (!Number.isFinite(pct)) return null;
  return CONDITION_SCALE.find((s) => pct <= s.wearTo) || CONDITION_SCALE[CONDITION_SCALE.length - 1];
}

const BAD = (r) => r <= 1.5;

// Корректировка «из состояния from в состояние to». Возвращает
// { value, invalid } или null, если пара методологией не рассчитывается.
export function conditionCorrection(from, to) {
  const a = scaleOf(from);
  const b = scaleOf(to);
  if (!a || !b) return null;
  if (a.label === b.label) return { value: 1, invalid: false };
  // Нерассчитываемые пары (пустые ячейки методологии): «Неудовлетворительное»
  // сравнивается только с «Требует ремонта» и «Требует капитального ремонта»;
  // от «Требует капитального ремонта» не приводят к «Отличному» и
  // «Отличному / хорошему».
  if ((a.rank === 1 && b.rank > 2) || (b.rank === 1 && a.rank > 2)) return null;
  if (a.rank === 1.5 && b.rank >= 4.5) return null;
  const value = (100 - a.repair) / (100 - b.repair);
  return { value, invalid: BAD(a.rank) || BAD(b.rank) };
}

export const fmtCorr = (v) => v.toFixed(2).replace('.', ',');
