// Поля карточки механизма по категориям.
//
// Иерархия класс → подгруппа → тип приходит из таблицы (mechClassifier.js,
// собирается скриптом). Параметры в таблице записаны сводно — «Марка (модель)
// и заводской номер», «Основные технические характеристики (для ПК —
// процессор, объём ОЗУ и накопителя…)», «Тип охлаждения (масляное, сухое…)», —
// и по три-пять на подгруппу. Для карточки этого мало и неудобно (задача
// пользователя 17.09.2026): здесь каждый сводный параметр разбит на отдельные
// поля, перечисления в скобках стали списками, величины — числом с единицей
// измерения, а характеристики, которые зависят от типа (у ноутбука одни, у
// принтера другие), заданы на тип.
//
// Состав полей — ЧЕРНОВИК на согласование с пользователем: сведён по таблице и
// листу «Схема», проверяемым документом служит docs/mech-polya.xlsx
// (tools/docs/build_mech_fields.py).
//
// Устройство записи подгруппы:
//   country  — спрашивать ли страну происхождения. Только у значимого
//              оборудования (станки, линии, энергетика, медицина, лаборатория):
//              у мебели и оргтехники страна для оценки не важна (решение
//              пользователя 17.09.2026);
//   main     — основные параметры: стоят сразу под наименованием;
//   extra    — дополнительные параметры;
//   byType   — уточнение на тип: { main, extra, omit } — добавить поля и
//              убрать ненужные (по ключу).
//
// Поле: { key, label, type, units, options, hint }
//   type   — text | num | int | select | date;
//   units  — единицы числа: одна — пишется в подписи («Длина, мм»), несколько —
//            выбираются списком рядом с числом;
//   key    — устойчивое имя: значение хранится по нему, и одинаковые ключи в
//            разных подгруппах сохраняют введённое при смене подгруппы.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: состав полей — справочник, который правят без
// программиста. Здесь он в коде макета; на сервере нужны версии состава и
// перенос значений при его правке.

const text = (key, label, o = {}) => ({ key, label, type: 'text', ...o });
const num = (key, label, units = [], o = {}) => ({ key, label, type: 'num', units: [].concat(units), ...o });
const int = (key, label, o = {}) => ({ key, label, type: 'int', ...o });
const sel = (key, label, options, o = {}) => ({ key, label, type: 'select', options, ...o });
const date = (key, label, o = {}) => ({ key, label, type: 'date', ...o });
const yes = (key, label) => sel(key, label, ['Да', 'Нет']);

