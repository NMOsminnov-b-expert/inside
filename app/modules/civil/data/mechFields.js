// --- Разрешение состава полей для единицы -----------------------------------

function merge(base, over) {
  if (!over) return base;
  const omit = new Set(over.omit || []);
  const keep = (list) => list.filter((f) => !omit.has(f.key));
  const add = (list, more) => {
    const have = new Set(list.map((f) => f.key));
    return list.concat((more || []).filter((f) => !have.has(f.key)));
  };
  return {
    country: base.country,
    main: add(keep(base.main), over.main),
    extra: add(keep(base.extra), over.extra),
  };
}

// Состав полей единицы по её классу, подгруппе и типу. null — классификация
// ещё не выбрана настолько, чтобы знать поля.
export function fieldsFor(cls, sub, type) {
  if (MECH_CLASS_FIELDS[cls]) return MECH_CLASS_FIELDS[cls];
  const s = (MECH_FIELDS[cls] || {})[sub];
  if (!s) return null;
  const base = { country: !!s.country, main: s.main || [], extra: s.extra || [] };
  return merge(base, (s.byType || {})[type]);
}
