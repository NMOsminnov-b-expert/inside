// Поля карточки транспортного средства по типу ТС.
//
// Состав — как в карточке ТС из ветки TS-Daniil (app/modules/vehicle): одно и
// то же ТС должно описываться одинаково, чем бы оно ни было заведено —
// объектом оценки или объектом имущества в составе другого объекта.
//
// Сверх той карточки добавлено только то, что ЕСТЬ В ТЕХПАСПОРТЕ либо
// ВЫЯВЛЯЕТСЯ ПРИ ОСМОТРЕ (указание пользователя 17.09.2026: «в техпаспорте
// далеко не всегда это указано… либо может быть выявлено»):
//   из техпаспорта — мощность двигателя, разрешённая максимальная масса,
//     категория ТС, страна-изготовитель, количество мест;
//   при осмотре — пробег по одометру, наработка спецтехники, состояние,
//     колёсная формула, тормозная система прицепа.
// Учётные сведения из бухгалтерского баланса (инвентарный номер, год ввода в
// эксплуатацию, балансовая стоимость) сюда не входят: их берут не из
// техпаспорта и не глазами.
//
// Устройство записи типа:
//   main   — основные характеристики: стоят сразу под маркой и номером;
//   extra  — дополнительные.
// Описание поля и его отрисовка — общие для модуля (parts/fields.js).
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: состав полей — справочник, который правят без
// программиста; здесь он в коде макета.
import { text, num, int, sel, multi } from '../parts/fields.js';

// Тип ТС — корень каскада: от него зависит весь набор характеристик.
export const VEHICLE_TYPES = [
  'Легковое',
  'Грузовое',
  'Спецтехника',
  'Прицепы и полуприцепы',
];

// --- Поля, общие для нескольких типов ---------------------------------------
// Одинаковый ключ — одно и то же поле: при смене типа значение остаётся.
const ENGINE_VOLUME = int('engineVolume', 'Рабочий объём двигателя, см³');
const ENGINE_POWER = num('enginePower', 'Мощность двигателя', ['л.с.', 'кВт']);
const GEARBOX = sel('gearbox', 'Тип КПП', ['МКПП', 'АКПП', 'Вариатор']);
const FUEL = multi('fuel', 'Тип топлива с завода', ['Бензин', 'Дизель', 'Газ', 'Электро', 'Гибрид']);
const STEERING = sel('steering', 'Расположение руля', ['Справа', 'Слева']);
const LOAD = num('loadCapacity', 'Грузоподъёмность', ['т', 'кг']);
const GROSS = num('grossMass', 'Разрешённая максимальная масса', ['т', 'кг']);
const FEATURES = text('features', 'Прочие особенности');

// Выявляется при осмотре, а не читается из документа.
const MILEAGE = int('mileage', 'Пробег по одометру, км');
const CONDITION = sel('condition', 'Состояние', ['На ходу', 'Требует ремонта', 'Не на ходу',
  'Разукомплектовано']);
const WHEELS = text('wheelFormula', 'Колёсная формула', { hint: 'Например: 4x2, 6x4' });

const CARGO_TYPES = ['Бортовой', 'Тентованный', 'Фургон', 'Изотермический', 'Рефрижератор', 'Самосвал',
  'Седельный тягач', 'Автовоз', 'Контейнеровоз', 'Цистерна', 'Длинномер', 'Манипулятор', 'Бетоносмеситель',
  'Бетононасос', 'Мусоровоз', 'Снегоуборщик', 'Скотовоз', 'Зерновоз', 'Трал'];

const SPECIAL_TYPES = ['Погрузчик', 'Экскаватор', 'Бульдозер', 'Грейдер', 'Фронтальный погрузчик',
  'Вилочный погрузчик', 'Трактор', 'Автокран', 'Каток', 'Самосвал', 'Трал', 'Мусоровоз', 'Поливомоечная',
  'Манипулятор', 'Автовышка', 'Пожарная', 'Лестница', 'Автоцистерна', 'Бензовоз', 'Водовоз', 'Бетоносмеситель'];

const TRAILER_TYPES = ['Прицеп', 'Полуприцеп'];

const BODY_TYPES = ['Тент', 'Платформа', 'Рефрижератор', 'Самосвал', 'Бортовой', 'Цельный фургон',
  'Цистерна', 'Животновоз', 'Автовоз', 'Иное'];

export const VEHICLE_FIELDS = {
  'Легковое': {
    main: [
      text('body', 'Тип кузова'),
      ENGINE_VOLUME, ENGINE_POWER, GEARBOX, FUEL,
    ],
    extra: [
      STEERING,
      int('seats', 'Количество мест'),
      MILEAGE, CONDITION, FEATURES,
    ],
  },

  'Грузовое': {
    main: [
      sel('cargoType', 'Тип', CARGO_TYPES),
      LOAD, GROSS, ENGINE_VOLUME, ENGINE_POWER, GEARBOX, FUEL,
    ],
    extra: [STEERING, WHEELS, MILEAGE, CONDITION, FEATURES],
  },

  'Спецтехника': {
    main: [
      sel('specialType', 'Тип', SPECIAL_TYPES),
      LOAD, ENGINE_VOLUME, ENGINE_POWER, GEARBOX, FUEL,
    ],
    extra: [
      STEERING, WHEELS, MILEAGE,
      int('engineHours', 'Наработка, моточасы'),
      CONDITION, FEATURES,
    ],
  },

  'Прицепы и полуприцепы': {
    main: [
      sel('trailerType', 'Тип', TRAILER_TYPES),
      sel('body', 'Тип кузова', BODY_TYPES),
      LOAD, GROSS,
      int('axles', 'Количество осей'),
    ],
    extra: [
      sel('brakes', 'Тормозная система', ['Пневматическая', 'Гидравлическая', 'Инерционная',
        'Без тормозов']),
      CONDITION, FEATURES,
    ],
  },
};

// «Иное» в типе кузова прицепа открывает поле для своего значения — так было в
// карточке ТС как объекта оценки, и это единственный случай, когда список
// дополняется вручную.
export const OTHER_BODY = text('otherBody', 'Укажите тип кузова');

// Состав полей по типу ТС. null — тип ещё не выбран, и полей не знаем.
export function vehicleFieldsFor(type, params) {
  const d = VEHICLE_FIELDS[type];
  if (!d) return null;

  const main = (d.main || []).slice();
  const at = main.findIndex((f) => f.key === 'body');
  if (at >= 0 && (params || {}).body === 'Иное') main.splice(at + 1, 0, OTHER_BODY);

  return { main, extra: d.extra || [] };
}
