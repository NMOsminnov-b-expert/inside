// Учётные и регистрационные сведения — одни на все типы ТС: их спрашивают у
// любой машины, и от типа они не зависят.
export const VEHICLE_REG_FIELDS = [
  text('sts', 'Свидетельство о регистрации (СТС)'),
  date('stsDate', 'Дата регистрации'),
  text('pts', 'Паспорт ТС (ПТС)'),
  sel('condition', 'Состояние', ['На ходу', 'Требует ремонта', 'Не на ходу', 'Разукомплектовано']),
];

// Состав полей по типу ТС. null — тип ещё не выбран, и полей не знаем.
export function vehicleFieldsFor(type) {
  const d = VEHICLE_FIELDS[type];
  if (!d) return null;
  return { main: d.main || [], extra: d.extra || [] };
}
