// Фабрика особенностей этого модуля (её использует и сид, и перенос старых
// текстовых полей). Отдельно от заметок намеренно: механики похожи, но это
// разные сущности — у особенности нет отметки «выполнено», зато в будущем
// появится влияние на оценку (Л3.6, Л4.5).
let specialSeq = 1;

export const SPECIAL_PLACEHOLDER = 'Что именно отличает объект — для оценки';

export function mkSpecial(text, date) {
  return {
    id: 's' + (specialSeq++),
    text: text || '',
    // Дату записи показываем в блоке; при переносе старых полей её взять
    // неоткуда, поэтому там она остаётся пустой.
    date: date || '',
  };
}
