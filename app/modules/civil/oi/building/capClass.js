// Нумерация — как в таблицах методологии: 4 — низший, 1 — высший; «I —
// низший» в её тексте о производственных — опечатка (пользователь 25.09.2026).
const POCKETS = [[0.33, 4], [0.55, 3], [0.77, 2], [Infinity, 1]];
export const POCKET_BANDS = [[null, 0.33, 4], [0.33, 0.55, 3], [0.55, 0.77, 2], [0.77, 1, 1]];

// Минимум К по виду — произведение наименьших коэффициентов (методология:
// гражданские 0,14, производственные 0,12).
export const minScore = (kind) => (SIGNS[kind] || []).reduce((a, sign) => a
  * Math.min(...(sign.height ? sign.height.map((b) => b[1]) : sign.options.map((o) => o[1]))), 1);
const CLASS_NAME = { 1: 'Первого класса', 2: 'Второго класса', 3: 'Третьего класса', 4: 'Четвертого класса' };
const GROUP_NAME = {
  admin: 'Административные/жилые/коммерческие/офисные/торговые помещения',
  prod: 'Производственно-складские помещения',
};
export const OTHER_NAME = 'Прочие постройки низкого качества строительства и некапитальные постройки';

export const kindOf = (oi) => oi.litKind || '';
export const signsOf = (oi) => (oi.capSigns = oi.capSigns || {});
export const pickedOf = (oi, key) => [].concat(signsOf(oi)[key] || []).filter(Boolean);

export function heightOf(oi) {
  const v = num((oi.heights || {}).int);
  return Number.isFinite(v) && v > 0 ? v : null;
}

// Диапазон высоты признака по числу из замеров.
export function heightBand(sign, h) {
  if (h === null) return null;
  return sign.height.find(([top]) => h <= top) || null;
}

// Коэффициент признака: у высоты — по диапазону, у выбора — по варианту, у
// нескольких вариантов — среднее. null — признак не заполнен.
export function signFactor(oi, sign) {
  if (sign.height) {
    const band = heightBand(sign, heightOf(oi));
    return band ? band[1] : null;
  }
  const picked = pickedOf(oi, sign.key);
  const list = picked.length ? picked : (sign.fallback ? [sign.fallback] : []);
  const f = list.map((v) => (sign.options.find((o) => o[0] === v) || [])[1]).filter((x) => typeof x === 'number');
  return f.length ? f.reduce((a, b) => a + b, 0) / f.length : null;
}

// Класс литеры: { key, label, missing }. key — значение oi.oiCategory, как у
// прежнего списка (admin-1 … prod-4, other), чтобы перечень и выгрузки
// читали класс по-старому.
export function capClass(oi) {
  const kind = kindOf(oi);
  if (!kind) return { key: '', label: '', missing: ['тип объекта имущества'] };
  if (kind === 'other') return { key: 'other', label: OTHER_NAME, missing: [] };
  const group = KINDS.find((k) => k.key === kind).group;
  const missing = [];
  let score = 1;
  SIGNS[kind].forEach((sign) => {
    const f = signFactor(oi, sign);
    if (f === null) missing.push(sign.height ? 'высота по внутренним замерам' : sign.label.toLowerCase());
    else score *= f;
  });
  if (missing.length) return { key: '', label: '', missing };
  const n = POCKETS.find(([top]) => score < top)[1];
  return { key: `${group}-${n}`, label: `${CLASS_NAME[n]} · ${GROUP_NAME[group]}`, missing: [] };
}

// Разбор К для показа: по каждому признаку — выбранное и коэффициент, затем
// произведение и класс. Показывается в карточке, чтобы было видно, откуда
// класс (замечание пользователя 25.09.2026: «вбил несколько вариантов и
// каждый раз 3 класс»).
export function capBreakdown(t) {
  const kind = kindOf(t);
  if (!kind || kind === 'other') return null;
  const factors = SIGNS[kind].map((sign) => {
    const f = signFactor(t, sign);
    let value;
    if (sign.height) {
      const band = heightBand(sign, heightOf(t));
      value = band ? band[2] : '';
    } else {
      const picked = pickedOf(t, sign.key);
      value = (picked.length ? picked : (sign.fallback ? [`${sign.fallback} (по умолчанию)`] : [])).join(' / ');
      if (picked.length > 1 && f !== null) value += ` — среднее из ${picked.length}`;
    }
    return { key: sign.key, label: sign.label, value, k: f };
  });
  const ready = factors.every((x) => x.k !== null);
  const k = ready ? factors.reduce((a, x) => a * x.k, 1) : null;
  const n = k === null ? null : POCKETS.find(([top]) => k < top)[1];
  return { kind, factors, k, n, min: minScore(kind) };
}

// Коэффициент капитальности К и класс — для сводной по объекту. У прочих
// построек К фиксированный — 0,05 (методология: навесы, ТП, КПП, охрана без
// разбора признаков). k = null — признаков не хватает.
export const K_OTHER = 0.05;

export function capScore(t) {
  const kind = kindOf(t);
  if (!kind) return { k: null, key: '', kind };
  if (kind === 'other') return { k: K_OTHER, key: 'other', kind };
  let score = 1;
  for (const sign of SIGNS[kind]) {
    const f = signFactor(t, sign);
    if (f === null) return { k: null, key: '', kind };
    score *= f;
  }
  return { k: score, key: capClass(t).key, kind };
}

// Класс пишется в запись сразу при расчёте: его читают перечень ОЦ, реестр и
// выгрузки, а не только карточка.
export function syncCapClass(oi) {
  const c = capClass(oi);
  oi.oiCategory = c.key;
  return c;
}

