// Координаты участка: проверка формата (ТЗ docs/tz/30-uchastok-pravki.md §5.1).
//
// Хранится строкой (`oi.gps`), разбор на числа — при выгрузке. Проверяется
// только формат: широта и долгота через запятую, точка как десятичный
// разделитель. Смысл проверки не в придирчивости, а в том, что перепутанные или
// оборванные координаты никак себя не проявляют — точка просто окажется не там,
// и заметят это не в карточке, а на карте, много позже.
//
// Заодно ловится самая частая ошибка ввода — координаты, вставленные с
// градусами («42°52'29"N») или с запятой в роли десятичного разделителя
// («42,874722 74,612222»): по такому значению не понять, где кончается широта.
//
// Границы намеренно шире Кыргызстана (широта 39–44, долгота 69–81): участок
// может быть заведён и по ошибочному адресу, и в приграничье, а сообщение об
// ошибке должно означать «так записать нельзя», а не «такого места не бывает».
// Проверку попадания в границы области сделает сервер — там есть справочник
// границ (ДЛЯ СЕРВЕРНОЙ ВЕРСИИ).

// Широта: −90…90, долгота: −180…180. Дробная часть необязательна.
const PAIR = /^(-?\d{1,3}(?:\.\d+)?)\s*,\s*(-?\d{1,3}(?:\.\d+)?)$/;

export function gpsError(value) {
  const v = String(value || '').trim();
  if (!v) return '';                  // пустое поле — не ошибка

  if (v.includes(';')) return 'Разделяйте широту и долготу запятой';

  const m = PAIR.exec(v);
  if (!m) {
    // Две группы цифр без запятой между ними — самый частый случай вставки.
    if (/^-?\d/.test(v)) return 'Формат: широта, долгота — например 42.874722, 74.612222';
    return 'Только цифры: широта, долгота — например 42.874722, 74.612222';
  }

  const lat = Number(m[1]);
  const lon = Number(m[2]);

  if (!(lat >= -90 && lat <= 90)) return 'Широта бывает от −90 до 90';
  if (!(lon >= -180 && lon <= 180)) return 'Долгота бывает от −180 до 180';

  // Широта и долгота перепутаны местами: в Кыргызстане широта всегда меньше
  // долготы, и обратный порядок — почти всегда ошибка вставки, а не участок в
  // другой части мира. Формат при этом верный, поэтому сообщение объясняет, что
  // именно не так, а набранное из поля не пропадает — его достаточно поменять
  // местами.
  if (lat > 60 && lon < 60) return 'Похоже, широта и долгота перепутаны местами';

  return '';
}
