import { uid, mechListLabel } from '../../parts/mechConstructor.js';

// Фабрика данных ОИ «Механизмы и оборудование» — по тому же приёму, что и
// карточка земельного участка (land-plot/oi/land/model.js): единый источник
// данных, который другие модули ОЦ (production, civil) подключают как свой
// вид ОИ, а не общий kernel-код (см. app/README.md, осознанное исключение из
// изоляции модулей).
//
// Один ОИ этого вида — контейнер, а не единица техники сама по себе: внутри
// него — список записей механизма (oi.mechanisms, тот же renderMechList/
// bindMechList, что и у карточки ОЦ этого модуля) — можно завести сразу
// несколько единиц техники в одном ОИ, не создавая для каждой отдельный ОИ
// (задача пользователя: раньше на каждый механизм требовался свой «+ Добавить
// ОИ»). Раньше здесь было два раздельных пункта меню — «Механизмы и
// производственное оборудование» и «Офисная техника и мебель» (card:'movable',
// два разных kind) — по решению пользователя объединены в один: офисная
// техника ничем принципиально не отличается от любого другого механизма,
// заводится тем же конструктором полей.
//
// nextId передаётся вызывающим модулем — у каждого свой счётчик
// (см. createLandOi — тот же приём).
export function createMechOi(rec, { nextId } = {}) {
  const mechanisms = [{ id: uid(), name: '', qty: 1, cost: 0, fields: [], photos: {} }];
  return {
    id: nextId('oi-mh'),
    card: 'mech',
    kind: 'МЕХ',
    mechanisms,
    // ДЛЯ ОБРАТНОЙ СОВМЕСТИМОСТИ: остальной код production/civil (сайдбар
    // просмотрщика, вкладка «Фото по литерам», лог действий по объекту,
    // тосты) читает oi.name у ЛЮБОГО вида ОИ напрямую — этих мест много и
    // они не завязаны на карточку конкретного вида. Вместо правки каждого,
    // здесь и в oi/mech/ctrl.js поддерживается синхронная копия — то же, что
    // вернул бы mechListLabel(oi.mechanisms), — обновляемая при каждой правке
    // состава механизмов.
    name: mechListLabel(mechanisms),
    docs: [],
    notes: [],
    photos: {},
  };
}
