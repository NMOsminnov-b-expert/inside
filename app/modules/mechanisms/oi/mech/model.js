// Фабрика данных ОИ «Механизмы» — по тому же приёму, что и карточка
// земельного участка (land-plot/oi/land/model.js): единый источник данных,
// который позже смогут импортировать другие модули ОЦ (production, civil —
// как свой вид ОИ «Механизмы»), а не общий kernel-код (см. app/README.md,
// осознанное исключение из изоляции модулей).
//
// Этот модуль («Механизмы и оборудование») своих ОИ этого вида не заводит —
// у него вообще нет объектов имущества (см. records.js) — createMechOi здесь
// экспортируется только чтобы карточка была самодостаточной и её можно было
// подключить из другого модуля без обратной зависимости на mechanisms/records.js.
//
// nextId передаётся вызывающим модулем — у каждого свой счётчик
// (см. createLandOi — тот же приём).
export function createMechOi(rec, { nextId } = {}) {
  return {
    id: nextId('oi-mh'),
    card: 'mech',
    kind: 'МЕХ',
    name: '',
    // Количество — обязательное поле конструктора (parts/mechConstructor.js),
    // по умолчанию 1: эта карточка ОИ всегда описывает один физический
    // экземпляр, «ещё один механизм» здесь — отдельный ОИ (+ Добавить ОИ), а
    // не рост qty; но поле общее с card/ocForm.js этого модуля (rec.mechanisms),
    // поэтому оно есть и тут — просто обычно остаётся равным 1.
    qty: 1,
    fields: [],
    docs: [],
    notes: [],
    photos: {},
  };
}
