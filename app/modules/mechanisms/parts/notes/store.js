// Фабрика заметок этого модуля (её использует и сид).
let noteSeq = 1;

export const NOTE_DEFAULT = 'Новая заметка';

// Шаблоны заметок (Л3.4): частые формулировки, чтобы не набирать руками.
// Выбранный шаблон подставляется в текст и остаётся редактируемым — к нему
// дописывают свободный текст. Состав списка — предмет согласования (вопрос 2.10
// в docs/tz/90-na-soglasovanie.md), формулировки здесь предварительные.
export const NOTE_TEMPLATES = [
  'Уточнить площадь по техпаспорту',
  'Нет правоустанавливающего документа',
  'Требуется повторный осмотр',
  'Расхождение техпаспорта и фактического состояния',
  'Не сходится этажность',
  'Запросить госакт на земельный участок',
  'Уточнить у собственника',
];

export function mkNote(text, done, author, date) {
  return {
    id: 'n' + (noteSeq++),
    text: text,
    done: !!done,
    // Автор и дата — кто и когда поставил заметку (Л3.4). У сидовых заметок их
    // нет: взять неоткуда, поэтому в показе будет прочерк.
    author: author || '',
    date: date || '',
  };
}
