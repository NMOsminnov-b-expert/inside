// Технические имена полей (пути JS-объекта) → человеческие подписи для лога
// действий (audit/model.js кладёт в строку лога путь через точку, а
// audit/view.js показывает то, что вернёт fieldLabel).
//
// Словарь СВОЙ на каждый модуль, а не общий в kernel (см. остальные модули) —
// здесь он короче всех: у записи нет ни кода ЕНИ, ни GPS, ни назначения по
// ТП, ни объектов имущества (см. manifest.js, records.js, card/ocForm.view.js).
// Единственное предметное поле — rec.mechanisms (состав механизмов записи:
// название/количество каждого и его конструктор полей).
//
// Подписи для rec.mechanisms сюда не входят вовсе — ни название/количество
// записи механизма, ни подписи её полей (последние вдобавок придумывает
// пользователь в рантайме, здесь заранее нечем их назвать). audit/model.js
// для всего этого сразу кладёт готовую человекочитаемую строку вида
// «Механизм «<название>»: Название» / «...: Количество» / «...: <label поля>»
// (см. walk() / diffMechanismsArray() / diffMechFieldsArray() там же), так
// что fieldLabel их просто не видит.
const COMMON = {
  // Запись ОЦ
  type: 'Тип ОЦ',
  category: 'Категория ОЦ',
  address: 'Адрес',
  city: 'Город',
  institution: 'Учреждение',
  podved: 'Подведомственность',
  status: 'Статус',
  owners: 'Собственники',
  users: 'Пользователи',
  'resp.gov': 'Ответственный от учреждения',
  'resp.cod': 'Оператор ЦОД',
  'resp.appr': 'Оценщик',
  'resp.insp': 'Осмотрщик',
};

// cardType — не используется (нет видов ОИ у этого модуля), параметр
// сохранён только для совместимости сигнатуры: и kernel/typeChange.js
// (смена типа ОЦ), и audit/view.js зовут fieldLabel(key, cardType) одинаково
// для всех пяти модулей.
export function fieldLabel(key, cardType) {
  return COMMON[key] || key;
}
