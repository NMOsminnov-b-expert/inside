// Статусы объекта оценки — шкала, как в рабочей системе (решение пользователя
// 21.09.2026: «как в системе»). Девять основных шагов идут по порядку, у двух
// есть боковые ветки: из «Готов к оценке» объект уходит в «Не подлежит
// оценке», из «Оценён» — в архив.
//
// Прежние пять статусов макета («… → На юридической экспертизе») заменены:
// юридической экспертизы в шкале системы нет.
//
// Переход — только на следующий шаг или в ветку текущего шага (решение
// пользователя 21.09.2026: «клик — следующий шаг»). Назад шкала не ведёт, из
// ветки дальше идти некуда.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: переходы здесь разрешены любому, кто открыл карточку.
// На сервере право на переход зависит от роли (ЦОД удостоверяет, осмотрщик
// отмечает осмотр, оценщик — оценку), и проверять его надо на сервере, а шкала
// лишь показывает доступные этой роли переходы. Развилка: хранить карту
// «переход → роли» в настройках или в коде процесса.

export const STATUS_MAIN = [
  'В заполнении',
  'Удостоверен по документам',
  'Направлен на осмотр',
  'Осмотрен',
  'Удостоверен после осмотра',
  'Готов к оценке',
  'В процессе оценки',
  'На проверке',
  'Оценён',
];

// Ветка: родительский шаг → боковой статус.
export const STATUS_BRANCH = {
  'Готов к оценке': 'Не подлежит оценке',
  'Оценён': 'В архиве',
};

export const STATUS_ALL = [...STATUS_MAIN, ...Object.values(STATUS_BRANCH)];

// Шкала — перечень шагов и боковые ветки. У объекта оценки — девять шагов, у
// объекта имущества — свои (kernel/oiStage.js); разметка и поведение одни.
export const OC_FLOW = { main: STATUS_MAIN, branch: STATUS_BRANCH };

const parentOf = (flow) => Object.fromEntries(Object.entries(flow.branch).map(([p, b]) => [b, p]));

export const isBranch = (status, flow = OC_FLOW) => status in parentOf(flow);

// Место статуса на основной линии. Ветка стоит на месте своего шага: объект,
// снятый с оценки, прошёл шкалу до шага, от которого она отходит.
export function stepOf(status, flow = OC_FLOW) {
  const main = isBranch(status, flow) ? parentOf(flow)[status] : status;
  return flow.main.indexOf(main);
}

// Куда можно перейти из статуса: следующий шаг и ветка этого шага.
export function nextOf(status, flow = OC_FLOW) {
  if (isBranch(status, flow)) return [];
  const i = flow.main.indexOf(status);
  // Статус не из шкалы (запись, заведённая до смены перечня): куда из него
  // идти, шкала не знает — статус правят в форме.
  if (i < 0) return [];
  const out = [];
  if (i + 1 < flow.main.length) out.push(flow.main[i + 1]);
  if (flow.branch[status]) out.push(flow.branch[status]);
  return out;
}
