// Нумерация блоков карточки — по порядку отрисовки.
//
// Зачем. Номера блоков («01 Общие параметры», «02 Площади и этажность»)
// расставлялись руками при вызове, и после каждого переноса блоков разъезжались.
// К 04.09.2026 дырка была в КАЖДОЙ карточке: у литеры в квартирном ОЦ шли
// 01·02·03·04·06, у гражданского 01…05·07, у участка 01·02·03·05 — потому что
// номер блока фотографий считался от индекса блока документов, который из
// карточки давно убрали.
//
// Человек по этим номерам ищет блок и ссылается на него в разговоре («смотри
// блок 05»), поэтому пропущенный номер читается как пропавший блок — именно так
// и было замечено (пользователь: «отсутствие блока 05 в производственном
// строении внутри квартиры»).
//
// Как пользоваться: в render() карточки завести счётчик и передавать его вызов
// каждому блоку по порядку. Тогда номер не может разойтись с составом, каким бы
// тот ни был у конкретного вида объекта:
//
//     const idx = blockNumbers();
//     `${generalCard(ctx, oi, idx())}
//      ${areasCard(ctx, oi, idx())}
//      ${rq.prod ? prodExtraCard(ctx, oi, idx()) : ''}
//      ${photosCard(ctx, oi, idx())}`
//
// Блок, который не отрисовался, номера не занимает — просто потому, что его
// idx() не вызвался.

export function blockNumbers(start = 1) {
  let n = start - 1;
  return () => ++n;
}
