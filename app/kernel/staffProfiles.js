// Профиль сотрудника — телефон и почта человека, который ведёт объекты
// (оператор ЦОД, оценщик, осмотрщик). Заводится один раз и подтягивается во
// все карточки, где человек назначен (решение пользователя 19.11.2026: «В
// карточках ОЦ должны быть ФИО и контактная информация оператора ЦОД»; ответ —
// «Профиль сотрудника», показывать у осмотрщика).
//
// Ключ — отображаемое имя: в макете сотрудник — строка с именем (см. resp.* у
// записи ОЦ и STAFF_ROLES в institutions.js), своей сущности у людей нет.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: профиль — учётная запись пользователя (id, ФИО,
// телефон, почта), карточка ОЦ ссылается на неё по id, а не по имени. Кто правит
// телефон и почту — сам сотрудник или администратор — решается вместе с разделом
// «Пользователи»; в макете профили демонстрационные и не правятся.

// Демо-данные: номера и адреса вымышленные (домен .example зарезервирован).
const DEMO = {
  'Айдай': { phone: '+996 555 000 101', email: 'staff-101@cod.example' },
  'Абдылдаев Айсултан Марсович': { phone: '+996 555 000 102', email: 'staff-102@cod.example' },
  'Молчанов Кирилл Витальевич': { phone: '+996 555 000 103', email: 'staff-103@cod.example' },
  'Карабекова Анара Тариеловна': { phone: '+996 555 000 104', email: 'staff-104@cod.example' },
  'Бабашова Даяна Алтынбековна': { phone: '+996 555 000 105', email: 'staff-105@cod.example' },
  'Осминнов Н.': { phone: '+996 555 000 106', email: 'staff-106@cod.example' },
};

// Профиль по имени: { name, phone, email }; без имени — null.
export function staffProfile(name) {
  const n = String(name || '').trim();
  if (!n) return null;
  const p = DEMO[n] || {};
  return { name: n, phone: p.phone || '', email: p.email || '' };
}
