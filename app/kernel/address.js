// Адрес объекта оценки и объектов имущества — сборка и свёртка.
//
// Решения пользователя 05.09.2026 по заметкам команды:
//   * у объекта оценки — город, район, микрорайон: то, что общее для всей
//     записи;
//   * у каждого объекта имущества — своя улица и дом, у квартиры ещё номер
//     квартиры; координаты GPS есть и у записи, и у каждого ОИ;
//   * в шапке и реестре адреса ОИ показываются свёрнутыми: одинаковые улица с
//     домом называются один раз, а номера квартир перечисляются списком —
//     иначе у дома с десятком квартир строка адреса становится нечитаемой.
//
// Почему в ядре: адрес собирают карточка ОЦ, шапка, реестр, архив и поиск —
// пять мест в пяти модулях. Держать в каждом свою сборку значит получить пять
// разных написаний одного и того же адреса.

const clean = (s) => String(s == null ? '' : s).trim();

// Верхняя часть адреса — из записи объекта оценки.
//
// Части склеиваются как записаны, без приписывания «г.» и «р-н»: населённый
// пункт бывает не только городом (село, посёлок), а деление — не только
// районом (область, айыл аймак). Подставлять сокращение значит однажды написать
// «г. Лебединовка».
export function ocAddressTop(rec) {
  if (!rec) return '';
  // С областью адрес идёт от общего к частному — область, район, населённый
  // пункт, микрорайон: так его и называют вслух, и так же стоят поля в блоке
  // «Местоположение» (правка 09.09.2026 по гражданскому зданию).
  //
  // Без области — прежний порядок: у типов ОЦ, которых правка не касалась,
  // адрес не должен перестраиваться сам собой.
  if (clean(rec.region)) {
    return [clean(rec.region), clean(rec.district), clean(rec.city), clean(rec.micro)]
      .filter(Boolean).join(', ');
  }
  return [clean(rec.city), clean(rec.district), clean(rec.micro)]
    .filter(Boolean).join(', ');
}

// Улица, дом и квартира САМОЙ записи.
//
// Изначально они были только у объектов имущества, и адрес записи собирался из
// них. С 09.09.2026 у гражданского здания адрес целиком живёт в объекте оценки
// — в блоке «Местоположение», а объекты имущества его больше не хранят
// (решение пользователя: «в ОИ их не будет»).
//
// Возвращает пустую строку, если у записи этих полей нет: тогда адрес
// собирается по-прежнему из ОИ, и типы ОЦ, которых правка не касалась,
// работают как работали.
export function ocAddressOwn(rec) {
  if (!rec) return '';
  return [
    clean(rec.street) && `ул. ${clean(rec.street)}`,
    clean(rec.house) && `д. ${clean(rec.house)}`,
    clean(rec.flat) && `кв. ${clean(rec.flat)}`,
  ].filter(Boolean).join(', ');
}

// Нижняя часть — из объекта имущества. Номер квартиры показывается только там,
// где он есть: у литеры или участка его не бывает.
export function oiAddressBottom(oi) {
  if (!oi) return '';
  return [
    clean(oi.street) && `ул. ${clean(oi.street)}`,
    clean(oi.house) && `д. ${clean(oi.house)}`,
    clean(oi.flat) && `кв. ${clean(oi.flat)}`,
  ].filter(Boolean).join(', ');
}

// Полный адрес одного ОИ: верх записи плюс его собственная часть.
export function oiFullAddress(rec, oi) {
  return [ocAddressTop(rec), oiAddressBottom(oi)].filter(Boolean).join(', ');
}

// Свёртка адресов ОИ: группируем по «улица + дом», квартиры собираем списком.
// Возвращаем строки вида «ул. Киевская, д. 218 — кв. 1, 5, 7».
export function groupedOiAddresses(rec) {
  const list = (rec && rec.oi) || [];
  const groups = [];

  list.forEach((oi) => {
    const street = clean(oi.street);
    const house = clean(oi.house);
    if (!street && !house) return;

    const key = `${street}|${house}`;
    let g = groups.find((x) => x.key === key);
    if (!g) {
      g = { key, street, house, flats: [] };
      groups.push(g);
    }

    const flat = clean(oi.flat);
    // Один и тот же номер квартиры дважды в списке не нужен: две записи на одну
    // квартиру бывают (например, доли), а адрес у них один.
    if (flat && !g.flats.includes(flat)) g.flats.push(flat);
  });

  return groups.map((g) => {
    const base = [g.street && `ул. ${g.street}`, g.house && `д. ${g.house}`]
      .filter(Boolean).join(', ');
    return g.flats.length ? `${base} — кв. ${g.flats.join(', ')}` : base;
  });
}

// Адрес записи целиком: верх плюс свёрнутые адреса ОИ. Это то, что видно в
// шапке карточки, в реестре и в архиве.
export function ocFullAddress(rec) {
  const top = ocAddressTop(rec);

  // Адрес записан у самой записи — берём его: объекты имущества своей улицы
  // больше не имеют, и собирать её оттуда нечего.
  const own = ocAddressOwn(rec);
  if (own) return [top, own].filter(Boolean).join(', ');

  const parts = groupedOiAddresses(rec);
  if (!parts.length) return top;
  return [top, parts.join('; ')].filter(Boolean).join(', ');
}

// Записать собранный адрес в rec.address.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: здесь адрес — производное значение, которое держится в
// записи ради совместимости (его читают реестр, поиск, архив и лог). На сервере
// это либо вычисляемое поле представления, либо денормализованная колонка,
// которую пересчитывает сам сервер при правке частей адреса.
export function syncOcAddress(rec) {
  if (!rec) return '';
  rec.address = ocFullAddress(rec);
  return rec.address;
}

// Разбор адреса, набранного или вставленного одной строкой (требование
// пользователя 09.09.2026: «туда можно кинуть адрес, а то, что найдётся,
// раскидается по полям»).
//
// Разбираем по маркерам — «обл.», «р-н», «г.», «мкр.», «ул.», «д.», «кв.»: их
// пишут почти всегда, и по ним часть адреса узнаётся однозначно. Что не
// опознано — не трогаем: пустое поле честнее угаданного неверно.
//
// Части без маркера читаются по месту: число после улицы — дом, а первое слово
// без маркера, если населённый пункт ещё не найден, — он и есть. Так строка
// «Бишкек, Киевская 218» тоже раскладывается.
const MARKERS = [
  ['region', /^(обл\.?|область)\s+|\s+(обл\.?|область)$/i],
  ['district', /^(р-?н|район)\s+|\s+(р-?н|район)$/i],
  ['city', /^(г\.?|гор\.?|город|с\.?|село|пгт|пос\.?|посёлок|поселок|айыл)\s+/i],
  ['micro', /^(мкр\.?|микрорайон|м-?н)\s+/i],
  ['street', /^(ул\.?|улица|пр\.?|проспект|пер\.?|переулок|б-?р|бульвар)\s+/i],
  // Номер после маркера обязателен: без него «д.» срезало первую букву любого
  // слова на «д», и «Дружбы 7» становилось домом «ружбы 7».
  ['house', /^(д\.?|дом|№)\s*(?=\d)/i],
  ['flat', /^(кв\.?|квартира|оф\.?|офис)\s*(?=\d)/i],
];

const STRIP = new Set(['street', 'house', 'flat']);

// Маркеры, которые встречаются ВНУТРИ куска, а не только в его начале. Кадастр
// отвечает «мкр. Асанбай, д. 50 кв. 80» — дом и квартира в одной части, без
// запятой между ними. Разбор только по запятым отдавал «Дому» всё целиком
// («50 кв. 80»), а «Квартира» оставалась пустой (замечание пользователя
// 11.09.2026).
//
// Режем перед маркером, а не по нему: сам маркер нужен следующему куску, чтобы
// тот опознался обычным образом. Область, район и населённый пункт сюда не
// входят — их пишут через запятую, а «с.» посреди строки чаще окажется частью
// названия, чем началом села.
const INNER = /\s+(?=(?:д|дом|кв|квартира|оф|офис|№)\.?\s*\d)/gi;

// Кусок из одного маркера — «ул.», «д.», «кв.» — значения не несёт.
const ONLY_MARKER = /^(обл|область|р-?н|район|г|гор|город|с|село|пгт|пос|посёлок|поселок|айыл|мкр|микрорайон|м-?н|ул|улица|пр|проспект|пер|переулок|б-?р|бульвар|д|дом|кв|квартира|оф|офис)\.?$/i;

// Разрезать кусок адреса на части по маркерам внутри него.
function splitInner(part) {
  // Голые маркеры выбрасываем и когда кусок разрезался, и когда нет: «ул. д. 50»
  // распадается на «ул.» и «д. 50», и вернуть тут исходный кусок значило бы
  // снова записать дом в улицу — ровно то, что и ломало адрес.
  const pieces = part.split(INNER).map((x) => x.trim())
    .filter((x) => x && !ONLY_MARKER.test(x));
  return pieces.length ? pieces : [];
}

export function parseAddress(text) {
  const out = {};
  const rest = [];

  String(text || '').split(',')
    .map((x) => x.trim()).filter(Boolean)
    .flatMap(splitInner)
    .forEach((part) => {
    const hit = MARKERS.find(([, re]) => re.test(part));

    // Маркер опознан, а поле уже занято — это второе значение того же вида
    // («кв. 80» после уже найденной квартиры). Девать его некуда, а в разбор
    // «по месту» ниже его пускать нельзя: там оно стало бы улицей.
    if (hit && out[hit[0]]) return;

    if (hit) {
      // Маркер оставляем в значении: «г. Бишкек» и «ул. Киевская» так и пишут,
      // а поле «Дом» хранит номер — там маркер убираем.
      const [key, re] = hit;
      // «ул.», «д.» и «кв.» приписывает сборщик (ocAddressOwn), поэтому из
      // значения их убираем — иначе получалось «ул. ул. Масалиева». А «г.»,
      // «р-н», «мкр.» и «область» остаются частью значения: их пишут по-разному
      // (город, село, айыл), и подставлять своё сокращение нельзя.
      let value = STRIP.has(key) ? part.replace(re, '').trim() : part;

      // «ул. Ахунбаева 119» — номер дома приписан к улице (так пишет Кадастр).
      // Отделяем, если дом ещё не найден: иначе номер остался бы частью
      // названия улицы и в поле «Дом» ничего бы не попало.
      if (key === 'street' && !out.house) {
        const withHouse = value.match(/^(.+?)[\s,]+(\d+[а-яa-z/-]*)$/i);
        if (withHouse) {
          value = withHouse[1].trim();
          out.house = withHouse[2];
        }
      }

      out[key] = value;
      return;
    }
    rest.push(part);
  });

  rest.forEach((part) => {
    // «Киевская 218» — улица с домом в одной части.
    const withHouse = part.match(/^(.+?)\s+(\d+[а-яa-z/-]*)$/i);
    if (withHouse && !out.street) {
      out.street = withHouse[1].trim();
      if (!out.house) out.house = withHouse[2];
      return;
    }
    if (!out.city) { out.city = part; return; }
    if (!out.street) { out.street = part; return; }
    if (!out.house && /^\d/.test(part)) out.house = part;
  });

  return out;
}
