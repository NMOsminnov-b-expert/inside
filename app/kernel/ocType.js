// Какой тип объекта оценки открыт сейчас.
//
// Зачем понадобилось. Карточки видов имущества переиспользуются между типами
// ОЦ: карточка квартиры живёт в модуле «жилое здание (квартира)», а
// открывается во всех пяти; карточка участка — в land-plot, а открывается тоже
// во всех. Вместе с карточкой в чужой модуль приезжают и её импорты, в том
// числе `data/opts.js` — а там тип ОЦ был зашит константой:
//
//     const TYPE_ID = 'apartment';
//
// Из-за этого квартира, заведённая в гражданском здании, читала справочники
// каталога «Жилое здание (квартира)». Слоты карточки квартиры в каталоге
// гражданского при этом существовали, были видны в разделе «Справочники» и
// правились — и не влияли ни на что. Настройка, которая молча ничего не делает,
// хуже отсутствующей: человек считает, что настроил (найдено сверкой 04.09.2026,
// решение пользователя — привязать справочники к типу ОЦ, в котором карточка
// открыта).
//
// Почему это состояние, а не аргумент. Тип ОЦ пришлось бы протаскивать через
// каждый вызов opt() — а их сотни, и часть из них в местах, где нет ни ctx, ни
// записи (например, фабрики строк развёртки этажей). Модулей на экране всегда
// ровно один: его main() и объявляет, какой тип открыт. Так что это не
// «глобальная переменная вместо параметра», а описание того, что сейчас на
// экране.
//
// Кто ставит: main() каждого модуля ОЦ (app/modules/<тип>/index.js) при входе.
// Кто читает: data/opts.js модулей — и через них все карточки.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: здесь это переменная в памяти вкладки, потому что
// открытый экран один. На сервере справочники запрашиваются вместе с записью, и
// тип ОЦ приходит из самой записи — тогда этот модуль не нужен вовсе, а opt()
// получает перечень из ответа.

let active = null;

export function setActiveOcType(typeId) {
  active = typeId || null;
}

// Пустое значение возможно на страницах вне модулей ОЦ (учреждения, документы,
// справочники): там вызывающая сторона подставляет свой запасной вариант.
export function activeOcType() {
  return active;
}
