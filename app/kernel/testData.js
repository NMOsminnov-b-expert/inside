// Включено — видны демо-записи засева (сид) и сгенерированный объём реестра. Выключено — они скрыты: в реестрах,
// счётчиках, поиске, срезах и у регионала видны только записи, заведённые вручную. Скрытие — только при показе
// (модули фильтруют сводки): сами записи остаются в памяти, иначе сохранение сочло бы засев удалённым и унесло
// удаление в файл сотрудника (kernel/persist.js). Переключение перезагружает страницу — все экраны берут данные
// заново.
//
// Состояние — в localStorage этого браузера (настройка макета, а не данные).
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: тестовых данных на сервере нет — тумблер уходит вместе с засевом.
const KEY = 'inside.testData';

let on = true;
try { on = localStorage.getItem(KEY) !== 'off'; } catch { on = true; }

export const testDataOn = () => on;

export function setTestDataOn(v) {
  try { localStorage.setItem(KEY, v ? 'on' : 'off'); } catch { /* без хранилища — только до перезагрузки */ }
  location.reload();
}

// Отбор показа: seedIds — номера записей засева модуля, isBulk — признак сгенерированной записи.
export const shownBy = (seedIds, isBulk = () => false) => (rec) => on || !(seedIds.has(rec.id) || isBulk(rec.id));
