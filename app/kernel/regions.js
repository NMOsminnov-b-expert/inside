export const SEP = ' / ';

export function regionTree() {
  return TREE;
}

// Все возможные значения поля «регион» — плоским списком путей. По нему идут и
// поиск при выборе, и проверка «есть ли такой регион».
export function regionPaths() {
  const out = [];

  TREE.forEach((area) => {
    out.push({ path: area.name, level: 1 });
    (area.children || []).forEach((district) => {
      const dPath = area.name + SEP + district.name;
      out.push({ path: dPath, level: 2 });
      (district.children || []).forEach((place) => {
        out.push({ path: dPath + SEP + place.name, level: 3 });
      });
    });
  });

  return out;
}

// Разбор строки на части: то, что показывает карточка и по чему группирует
// раздел «Учреждения».
export function splitRegion(value) {
  return String(value || '').split('/').map((x) => x.trim()).filter(Boolean);
}

export function areaOf(value) {
  return splitRegion(value)[0] || '';
}

export function districtOf(value) {
  return splitRegion(value)[1] || '';
}

export function placeOf(value) {
  return splitRegion(value)[2] || '';
}

// Поиск при выборе: слова запроса ищутся в любой части пути, поэтому «сокулук
// кызыл» находит «Чуйская область / Сокулукский район / с. Кызыл-Туу».
export function searchRegions(q, limit = 40) {
  const words = String(q || '').toLowerCase().split(/\s+/).filter(Boolean);
  const all = regionPaths();
  if (!words.length) return all.filter((x) => x.level <= 2).slice(0, limit);

  return all
    .filter((x) => {
      const hay = x.path.toLowerCase();
      return words.every((w) => hay.includes(w));
    })
    .slice(0, limit);
}

