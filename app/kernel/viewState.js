// Вид экрана переживает перезагрузку и уход с экрана.
//
// Решение пользователя 09.10.2026 по код-ревью: «Вот в каком виде мы страницу
// закрываем, в таком же она потом должна открываться. Относится ко всей
// динамике по всему макету». Прежде вид сохраняли только модули
// недвижимости, и каждый по-своему; ТС, механизмы и страницы ядра
// (учреждения, справочники, архив, документы) открывались каждый раз заново.
//
// Сохраняется то, что задаёт вид: раскрытые и свёрнутые блоки, просмотрщик и
// его размеры, столбцы, фильтры, поиск, выбранный узел и вкладка. Не
// сохраняется сиюминутное: открытые окна и выпадающие меню, выделение,
// черновики и правка «на месте» — после перезагрузки они мешали бы.
//
// ДЛЯ СЕРВЕРНОЙ ВЕРСИИ: вид живёт в хранилище браузера (kernel/persist.js,
// части «ui.*») — у каждого браузера свой. На сервере это личные настройки
// пользователя; развилка — хранить их на сервере (вид следует за человеком
// с машины на машину) или оставить в браузере (вид привязан к рабочему месту).
import { registerPersisted } from './persist.js';

// Состояние просмотрщика и шапки — одинаковое у всех модулей ОЦ
// (kernel/viewer/*, kernel/status/*).
export const VIEWER_KEEP = [
  'viewer', 'viewerDoc', 'viewerSidebar', 'viewerClosed', 'viewerDock',
  'splitVW', 'cmpSplit', 'cmpHidden', 'railCollapsed', 'statusCollapsed',
];

// obj — объект состояния экрана (меняется на месте), keep — его ключи,
// которые сохраняются. name — имя части снимка без «ui.».
export function persistView(name, obj, keep) {
  registerPersisted('ui.' + name, {
    snapshot: () => Object.fromEntries(keep.filter((k) => obj[k] !== undefined).map((k) => [k, obj[k]])),
    restore: (saved) => {
      if (!saved || typeof saved !== 'object') return;
      keep.forEach((k) => { if (saved[k] !== undefined) obj[k] = saved[k]; });
    },
  });
}

// То же для вида, который живёт не в одном объекте, а в переменных модуля —
// ширины перегородок и столбцов на страницах: take() отдаёт снимок, put(saved)
// раскладывает его обратно. Ширины, растянутые человеком, — тоже «вид, в
// котором закрыли».
export function persistSizes(name, take, put) {
  registerPersisted('ui.' + name, {
    snapshot: take,
    restore: (saved) => { if (saved && typeof saved === 'object') put(saved); },
  });
}
