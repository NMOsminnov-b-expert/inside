// Пустой пункт списка — один на весь макет.
//
// Раньше каждое поле писало его само, и в разметке жили разные слова: где-то
// «Не выбрано», где-то «Не указано». Аудит справочников 05.09.2026 нашёл и
// худший случай — поля, где рядом с пустым пунктом стоит содержательный ответ
// «Нет» или «Отсутствует» (сервитуты, каменистость, доступность полива у
// участка). В списке они читались как дубль: два пункта об одном и том же.
//
// Правило пользователя:
//   * пустой пункт называется «Не выбрано» — везде;
//   * а там, где в самом перечне есть ответ «Нет»/«Отсутствует», он называется
//     «Не заполнено»: так видно, что это отсутствие ответа, а «Нет» — ответ.
//
// Второе правило считается по значениям, а не перечисляется списком полей:
// перечни правятся из раздела «Справочники», и поле, которому такой ответ
// добавят завтра, должно получить верную подпись само.
const ANSWER_NO = /^(нет|отсутствует|отсутствуют)$/i;

export const EMPTY_LABEL = 'Не выбрано';
export const EMPTY_LABEL_WITH_NO = 'Не заполнено';

export function emptyLabel(values = []) {
  return values.some((v) => ANSWER_NO.test(String(v).trim()))
    ? EMPTY_LABEL_WITH_NO
    : EMPTY_LABEL;
}

// Готовый <option> для поля с выбором. Значение пустое — по нему поле и
// считается незаполненным.
export function emptyOptionHTML(values = []) {
  return `<option value="">${emptyLabel(values)}</option>`;
}
