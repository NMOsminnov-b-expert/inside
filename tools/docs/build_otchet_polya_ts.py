# Поэлементное состояние легкового — одна строка таблицы наличия, а не двенадцать.
COND = 'Состояние по элементам (таблица)'
def fold(label):
    return COND if label.startswith('Состояние ') else label


def catalog():
    js = ("import('./app/modules/vehicle/data/tsCatalog.js').then((m) => { const cats = {};"
          "for (const b of m.TS_BASES) (cats[b.category] = cats[b.category] || []).push(b.name);"
          "const res = {}; for (const [c, bs] of Object.entries(cats)) res[c] = {"
          "common: (m.TS_BASE_FIELDS_BY_CATEGORY[c] || m.TS_BASE_FIELDS).map((f) => f.label),"
          "bases: bs.map((b) => [b, (m.TS_SPECIAL[b] || []).map((f) => f.label)]) };"
          "res['Спецтехника'] = { common: m.TS_SELF_FIELDS.map((f) => f.label), bases: [] };"
          "console.log(JSON.stringify(res)); })")
    out = subprocess.run(['node', '--input-type=module', '-e', js], cwd=ROOT, capture_output=True, encoding='utf-8')
    data = json.loads(out.stdout)
    for info in data.values():
        info['common'] = list(dict.fromkeys(fold(f) for f in info['common']))
    return data


# --- разметка -------------------------------------------------------------------
def shade(cell, color):
    pr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear')
    sh.set(qn('w:color'), 'auto')
    sh.set(qn('w:fill'), color)
    pr.append(sh)


def repeat_header(row):
    pr = row._tr.get_or_add_trPr()
    el = OxmlElement('w:tblHeader')
    el.set(qn('w:val'), 'true')
    pr.append(el)


def table(doc, head, rows, widths=None, size=9):
    t = doc.add_table(rows=1, cols=len(head))
    t.style = 'Light Grid Accent 1'
    repeat_header(t.rows[0])
    for i, name in enumerate(head):
        t.rows[0].cells[i].text = name
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = str(v if v is not None else '')
    for row in t.rows:
        for i, c in enumerate(row.cells):
            for par in c.paragraphs:
                for run in par.runs:
                    run.font.size = Pt(size)
            if widths:
                c.width = widths[i]
    return t


def landscape(doc):
    sec = doc.add_section()
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    return sec


def build():
    data = catalog()
    doc = Document()
    doc.styles['Normal'].font.size = Pt(10)
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2)

    doc.add_heading('Поля карточки ТС по категориям', 0)

    # 1. Базы
    doc.add_heading('1. Базы внутри категорий', 1)
    doc.add_paragraph('Правило: где у баз категории одни и те же поля, выбора базы нет; где поля различаются, база '
                      'остаётся (решение пользователя 06.10.2026). «Прочее» — база для машины, не легшей ни в одну '
                      'другую, есть в каждой категории и в разбор не входит.')
    for cat, info in data.items():
        if cat == 'Спецтехника':
            continue
        doc.add_heading(cat, 2)
        doc.add_paragraph(BASE_NOTES.get(cat, ''))
        rows = [(b, ', '.join(f) or '—') for b, f in info['bases']]
        table(doc, ['База', 'Свои поля базы'], rows, [Cm(6), Cm(11)])

    # 2. Наличие полей
    landscape(doc)
    doc.add_heading('2. Наличие полей по категориям', 1)
    doc.add_paragraph('«есть» — поле в карточке категории; «база» — особое поле одной или нескольких баз; '
                      '«нелогично» — поле есть, но к категории не подходит (раздел 3). Категория «По техпаспорту» '
                      'не показана: в ней все общие поля.')
    bad = {(col, field) for cols, field, _, _ in FINDINGS for col in cols}
    order = []
    for cat, _ in COLS:
        for f in data[cat]['common'] + [x for _, fs in data[cat]['bases'] for x in fs]:
            if f not in order:
                order.append(f)
    rows = []
    for f in order:
        row = [f]
        for cat, short in COLS:
            info = data[cat]
            here = 'есть' if f in info['common'] else 'база' if any(f in fs for _, fs in info['bases']) else '—'
            row.append('нелогично' if here != '—' and (short, f) in bad else here)
        rows.append(row)
    t = table(doc, ['Поле'] + [s for _, s in COLS], rows, [Cm(7)] + [Cm(2.6)] * len(COLS), size=8)
    for row in t.rows[1:]:
        for c in row.cells[1:]:
            if c.text == 'нелогично':
                shade(c, 'F8D7D3')
            elif c.text == '—':
                shade(c, 'F2F2F2')

    # 3. Нелогичное
    doc.add_heading('3. Нелогичные поля', 1)
    doc.add_paragraph('Поле есть в карточке категории, но у машин этой категории его не бывает или оно повторяет '
                      'другое поле. Предложение «Вопрос» — решение за пользователем.')
    table(doc, ['Категория', 'Поле', 'Причина', 'Предложение'],
          [(', '.join(cols), field, why, what) for cols, field, why, what in FINDINGS],
          [Cm(4), Cm(4.5), Cm(11), Cm(5.5)])

    doc.save(OUT)
    return len(order), len(FINDINGS)


if __name__ == '__main__':
    n, k = build()
    print('docs/otchet-polya-ts.docx собран: полей %d, нелогичных мест %d' % (n, k))
