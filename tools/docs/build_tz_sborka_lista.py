def safe_out():
    """Файл, изменённый человеком после сборки, не перезаписывается
    (pered-pravkoy-fayla-proverit-chto-polzovatel-ego-ne-redaktiruet)."""
    global OUT
    if not os.path.exists(OUT):
        return
    try:
        who = Document(OUT).core_properties.last_modified_by or ''
    except Exception:
        who = '?'
    if who not in ('', 'python-docx'):
        OUT = OUT.replace('.docx', '.sborka.docx')
        print('docs/tz-sborka-lista.docx правил «%s» — не перезаписываю, сборка рядом' % who)


if __name__ == '__main__':
    safe_out()
    build()
    print('→', os.path.relpath(OUT, ROOT))
