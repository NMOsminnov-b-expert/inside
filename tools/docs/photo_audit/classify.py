def _lits(s):
    """Буквы литер из найденного списка: «а,б» → ['А','Б'], «б-в» → ['Б','В'], «а и а1» → ['А','А1']."""
    # латиница, похожая на кириллицу («лит c», «A»), — к кириллице: в базе литеры кириллические
    s = s.upper().replace('Ё', 'Е').translate(str.maketrans('ABCEHKMOPTX', 'АВСЕНКМОРТХ'))
    toks = re.split(r'\s*[,/;]\s*|\s+И\s+|\s*[-–]\s*(?=[А-ЯA-E])|\s+(?=[А-ЯA-E])', s)
    out = []
    for t in toks:
        t = re.sub(r'\s+', '', t)
        t = re.sub(r'^([А-ЯA-E])-(\d)', r'\1\2', t)      # «В-2» — это литера В2
        if t:
            out.append(t)
    return out


def roles(seg, level=None):
    raw = seg.strip()
    s = norm(seg)
    info = {}
    s = re.sub(r'\(\s*[+\-=]+\s*\)|\(\s*не\s*полн\w*\s*\)|[+=!]+|\(\s*\)', ' ', s)
    if GRP_FULL.match(re.sub(r'[+=!()\s]+$', '', s).strip()):
        return ['GRP'], info
    s = re.sub(r'[-\s]*осмотрено\s*$', '', s)
    s = re.sub(r'\s+', ' ', s).strip(' -_.,')
    R = []
    if not s:
        return ['NUM'], info
    # коды ЕНИ ищем раньше всего: 13-значный код в имени — это не пометка
    m = RX_ENI_FULL.search(s)
    if m:
        info['eni'] = m.group(0)
    if INV_RX.match(s):
        return ['EQP'], dict(info, inv=True)
    if NUM_RX.match(s):
        return ['NUM'], info
    if level == 2 and PERSON_RX.match(raw):
        return ['PERS'], info
    rest = s
    m = RX_ORG.match(s)
    if m and 'eni' not in info:
        nums = re.findall(r'\d+', m.group(1))
        if len(nums) >= 2 or (len(nums) == 1 and len(nums[0]) >= 2 and int(nums[0]) >= 16):
            if not FLOOR_RX.match(s):
                R.append('ORG'); info['org'] = m.group(1)
                rest = s[m.end():].strip(' .-_')
    if 'ORG' not in R:
        rest = RX_NUM_PREFIX.sub('', rest).strip(' .-_')
    if not rest:
        return R or ['NUM'], info
    if R and GRP_FULL.match(rest):
        return R, info
    if GRP_FULL.match(s):
        return R + ['GRP'], info
    if WRAP_FULL.match(rest):
        return R + ['WRAP'], info
    if GRP_FULL.match(rest):
        return R + ['GRP'], info
    raw_rest = re.sub(r'^[+\-\s\d.)_]*', '', raw).strip()
    if CONCAT_LIT.match(rest) and raw_rest.isupper() and rest not in BARE_BAD and len(set(rest)) == len(rest) \
            and list(rest) == sorted(rest, key='абвгдежзиклмноп'.index):
        return R + ['LIT'], dict(info, lits=[c.upper() for c in rest])
    if GRP_ABBR.match(rest) and raw_rest.isupper() and rest not in BARE_BAD and not LIT_BARE.fullmatch(rest):
        return R + ['GRP'], info
    mw = WRAP_PREFIX.match(rest)
    if mw:
        R.append('WRAP'); rest = rest[mw.end():].strip(' .-_')
    elif WRAP_SUFFIX.search(rest):
        R.append('WRAP'); rest = WRAP_SUFFIX.sub('', rest).strip(' .-_')
    if rest.startswith('и примеч') or not rest:
        return R or ['WRAP'], info

    nodoc = NODOC_RX.search(rest)
    if nodoc:
        R.append('NODOC'); rest = (rest[:nodoc.start()] + ' ' + rest[nodoc.end():]).strip(' -_.,()')
        if not rest:
            return R, info
    if LIT_WORD_ALONE.match(rest):
        return R + ['LIT'], dict(info, lits=[])
    lit = LIT_RX.search(rest)
    probe = (rest[:lit.start()] + ' ' + rest[lit.end():]) if lit else rest
    street = bool(STREET_TOK.search(probe)) or 'eni' in info
    # «теплица 3», «корпус 2»: номер при строении — не адрес, если нет явного признака улицы
    if street and 'eni' not in info and (BLD_RX.search(probe) or DOC_RX.search(probe))             and not STREET_EXPLICIT.search(probe) and not PLACE_TOK.search(probe):
        street = False
    place = bool(PLACE_TOK.search(probe))
    obj = OBJ_RX.search(rest)
    land = LAND_RX.search(rest)
    veh = bool(VEH_RX.search(rest)) or (bool(VEH_PLATE.search(rest)) and not street)
    if veh and not (obj or land) and not (street and not VEH_PLATE.search(rest) and not VEH_RX.search(rest)):
        return R + ['VEH'], info
    doc = DOC_RX.search(rest)
    lits = None
    if lit:
        lits = _lits(lit.group(1) or lit.group(2))
    else:
        d = LIT_DIGIT.search(rest)
        if d:
            lits = [d.group(1)]
        else:
            b = None if (street or place) else LIT_BARE.match(rest)
            if b and b.group(1).replace(' ', '') not in BARE_BAD and not (b.group(1) in ('в', 'и') and rest[b.end():].strip()) and len(b.group(1)) <= 30:
                cand = _lits(b.group(1))
                # голая буква допустима, только если после неё — этаж/категория/скобка или конец
                tail = rest[b.end():].strip()
                place_letter = len(cand) == 1 and cand[0] in ('Г', 'С', 'П', 'Д', 'Ш', 'У') and tail and tail[0] not in '(-–,:'
                if not place_letter and all(len(c) <= 4 for c in cand) and (not tail or tail[0] == '(' or re.match(r'^[-–,:]\s', tail) or FLOOR_RX.match(tail) or any(rx.search(' ' + tail) for _, rx in CAT_RX) or OBJ_RX.match(tail) or BLD_RX.match(tail)):
                    lits = cand
    if ROMAN_LIT.match(rest):
        return R + ['LIT'], dict(info, lits=[rest.upper()])
    if EQP_RX.search(rest) and not (place or STREET_EXPLICIT.search(rest)):
        return R + ['EQP'], info
    if LIT_WORD_ALONE.match(rest):
        R.append('LIT'); info['lits'] = []
        return R, info
    if lits:
        R.append('LIT'); info['lits'] = lits
    fl = FLOOR_RX.search(rest)
    if fl:
        R.append('FLOOR'); info['floor'] = fl.group(0)
    if doc and not lits:
        R.append('DOC')
    if street:
        R.append('ADDR'); info['addr'] = 'full'
    elif place:
        R.append('ADDR'); info['addr'] = 'place'
    cats = [c for c, rx in CAT_RX if rx.search(' ' + rest)]
    if cats and not ('ADDR' in R and cats == ['Земельный участок'] and land and not re.search(r'террит|територ|терет|двор', rest)):
        info['cat'] = cats; R.append('CAT')
    if land and 'CAT' not in R and not lits:
        R.append('LAND')
    bld = BLD_RX.search(rest)
    if bld and not lits:
        R.append('BLD'); info['bld'] = bld.group(0)
    if obj and not ('DOC' in R and 'ADDR' not in R):
        R.append('OBJ')
    if 'DOC' in R and 'ADDR' not in R and 'BLD' in R:
        R.remove('BLD')
    if not [r for r in R if r not in ('ORG', 'WRAP', 'NODOC')]:
        R.append('UNK' if 'ORG' not in R else 'ORGNAME')
    return R, info
