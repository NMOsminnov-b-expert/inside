def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    return struct.unpack('>II', head[16:24])


def bullet(doc, text):
    par = doc.add_paragraph(style='List Bullet')
    word, sep, rest = text.partition(': ')
    if sep and len(word) <= 60 and '.' not in word:
        par.add_run(word + ': ').bold = True
        par.add_run(rest)
    else:
        par.add_run(text)


def main():
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = 'Calibri'
    st.font.size = Pt(11)
    for sec in doc.sections:
        sec.left_margin = sec.right_margin = Cm(2)
        sec.top_margin = sec.bottom_margin = Cm(1.8)
    doc.add_heading('Веб-страница осмотрщика: функционал', level=0)
    meta = doc.add_paragraph(f'Состояние макета на {DATE}. Снимки экранов — на ширине телефона, данные '
                             'демонстрационные.')
    meta.runs[0].italic = True
    meta.runs[0].font.color.rgb = RGBColor(0x55, 0x60, 0x70)
    missing = []
    for item in C:
        kind = item[0]
        if kind in ('h1', 'h2', 'h3'):
            doc.add_heading(item[1], level={'h1': 1, 'h2': 2, 'h3': 3}[kind])
        elif kind == 'p':
            doc.add_paragraph(item[1])
        elif kind == 'ul':
            for t in item[1]:
                bullet(doc, t)
        elif kind == 'table':
            head, rows = item[1], item[2]
            tb = doc.add_table(rows=1, cols=len(head))
            tb.style = 'Light Grid Accent 1'
            tb.alignment = WD_TABLE_ALIGNMENT.CENTER
            for i, h in enumerate(head):
                tb.rows[0].cells[i].text = h
                tb.rows[0].cells[i].paragraphs[0].runs[0].bold = True
            for r in rows:
                cells = tb.add_row().cells
                for i, v in enumerate(r):
                    cells[i].text = v
            doc.add_paragraph()
        elif kind == 'img':
            path = os.path.join(SHOTS, item[1])
            if not os.path.exists(path):
                missing.append(item[1])
                continue
            w, h = png_size(path)
            # Узкий снимок телефона: ширина 6,5 см; длинный экран ограничен высотой страницы.
            if h / w * 6.5 > 22:
                doc.add_picture(path, height=Cm(22))
            else:
                doc.add_picture(path, width=Cm(6.5))
            cap = doc.add_paragraph(item[2])
            cap.runs[0].italic = True
            cap.runs[0].font.size = Pt(9)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    doc.save(OUT)
    print('→', OUT)
    if missing:
        print('Нет снимков (сначала shoot_opisanie_osmotrschika.py):', ', '.join(missing))


if __name__ == '__main__':
    main()
