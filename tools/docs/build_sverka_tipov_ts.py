def read(book):
    wb = load_workbook(book, read_only=True)
    data = {}
    for col in ('F', 'I'):
        ws = wb['Столбец %s' % col]
        data[col] = [(str(r[0]), r[1]) for r in ws.iter_rows(min_row=2, values_only=True) if r[0] is not None]
    wb.close()
    return data


def sheet(wb, title, head, rows, widths, colour=None):
    ws = wb.create_sheet(title)
    ws.append(head)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill('solid', fgColor='DCEBF8')
        c.alignment = Alignment(wrap_text=True, vertical='center')
    for r in rows:
        ws.append(list(r))
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top')
        if colour:
            fill = colour(row)
            if fill:
                for c in row:
                    c.fill = PatternFill('solid', fgColor=fill)
    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = ws.dimensions


def build(book):
    data = read(book)
    vals = {'I': [v for v, _ in data['I'] if v != '(пусто)'], 'F': [v for v, _ in data['F'] if v != '(пусто)']}
    res = subprocess.run(['node', '--input-type=module', '-e', JS, json.dumps(vals, ensure_ascii=False)], cwd=ROOT,
                         capture_output=True, encoding='utf-8')
    if res.returncode:
        raise SystemExit(res.stderr)
    found = json.loads(res.stdout)
    search = {v: (n, top) for v, n, top in found['I']}
    rows = []
    for v, n in data['I']:
        if v == '(пусто)':
            continue
        target, state = TARGET.get(v.lower(), ('не размечено', '?'))
        total, top = search.get(v, (0, []))
        ok = 'находит' if total else 'не находит'
        rows.append((v, n, target, state, ok, '; '.join(top)))
    rows.sort(key=lambda r: -r[1])
    wb = Workbook()
    wb.remove(wb.active)
    fill = {'нет': 'F8D7D3', 'частично': 'FFF1CC'}
    sheet(wb, 'Вид кузова (I)', ['Запись', 'Строк', 'Куда в карточке', 'В справочнике', 'Поиск «Вида объекта»',
                                  'Первые варианты поиска'], rows, [34, 9, 50, 14, 14, 70],
          lambda row: fill.get(row[3].value) or ('FFF1CC' if row[4].value == 'не находит' else None))
    frows = []
    cand = dict((v, c) for v, c in found['F'])
    for v, n in data['F']:
        if v == '(пусто)':
            continue
        got = ', '.join(cand.get(v, [])) or '—'
        frows.append((v, n, F_EXPECT.get(v.lower(), '?'), got))
    sheet(wb, 'Тип ТС (F)', ['Запись', 'Строк', 'Должна подбираться категория', 'Подбирает карточка'], frows, [24, 9, 40, 40],
          lambda row: 'F8D7D3' if row[3].value == '—' else None)
    total = sum(r[1] for r in rows)
    summary = [
        ('Записей вида кузова (без пустых)', len(rows), total),
        ('Есть в справочнике', sum(1 for r in rows if r[3] == 'есть'), sum(r[1] for r in rows if r[3] == 'есть')),
        ('Есть частично', sum(1 for r in rows if r[3] == 'частично'), sum(r[1] for r in rows if r[3] == 'частично')),
        ('Нет в справочнике', sum(1 for r in rows if r[3] == 'нет'), sum(r[1] for r in rows if r[3] == 'нет')),
        ('Поиск ничего не находит', sum(1 for r in rows if r[4] == 'не находит'), sum(r[1] for r in rows if r[4] == 'не находит')),
        ('Тип ТС без подбора категории', sum(1 for r in frows if r[3] == '—'), sum(r[1] for r in frows if r[3] == '—')),
    ]
    sheet(wb, 'Итог', ['Показатель', 'Значений', 'Строк реестра'], summary, [40, 12, 16])
    wb.move_sheet('Итог', offset=-2)
    wb.save(OUT)
    return summary


