class Doc:
    def __init__(self):
        self.d = Document()
        st = self.d.styles['Normal']
        st.font.name = 'Times New Roman'
        st.element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')
        st.font.size = Pt(12)
        pf = st.paragraph_format
        pf.space_after = Pt(0)
        pf.space_before = Pt(0)
        pf.line_spacing = 1.15
        for lvl, size in ((1, 14), (2, 13), (3, 12)):
            h = self.d.styles['Heading %d' % lvl]
            h.font.name = 'Times New Roman'
            # Шрифт темы (asciiTheme…) перебивает заданный — снимаем его.
            rf = h.element.rPr.rFonts
            for a in ('w:asciiTheme', 'w:hAnsiTheme', 'w:eastAsiaTheme', 'w:cstheme'):
                if rf.get(qn(a)) is not None:
                    del rf.attrib[qn(a)]
            for a in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
                rf.set(qn(a), 'Times New Roman')
            h.font.size = Pt(size)
            h.font.bold = True
            h.font.color.rgb = None
            h.paragraph_format.space_before = Pt(12 if lvl == 1 else 8)
            h.paragraph_format.space_after = Pt(6)
            h.paragraph_format.keep_with_next = True
        for s in self.d.sections:
            s.page_height, s.page_width = Cm(29.7), Cm(21.0)
            s.left_margin, s.right_margin = Cm(3.0), Cm(1.5)
            s.top_margin, s.bottom_margin = Cm(2.0), Cm(2.0)
        self.h = [0, 0, 0]
        self.p_no = 0
        self.tables = 0
        self._footer_numbers()

    def _footer_numbers(self):
        sec = self.d.sections[0]
        sec.different_first_page_header_footer = True
        par = sec.footer.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self._field(par, 'PAGE')

    @staticmethod
    def _field(par, code):
        run = par.add_run()
        for kind, text in (('begin', None), (None, code), ('separate', None), ('end', None)):
            if kind:
                el = OxmlElement('w:fldChar')
                el.set(qn('w:fldCharType'), kind)
            else:
                el = OxmlElement('w:instrText')
                el.set(qn('xml:space'), 'preserve')
                el.text = text
            run._r.append(el)

    def para(self, text, bold=False, align=None, indent=True, size=None, italic=False, space_after=3):
        p = self.d.add_paragraph()
        if align is not None:
            p.alignment = align
        else:
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        if indent:
            p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.space_after = Pt(space_after)
        r = p.add_run(text)
        r.bold = bold
        r.italic = italic
        if size:
            r.font.size = Pt(size)
        return p

    def heading(self, level, text):
        self.h[level - 1] += 1
        for i in range(level, 3):
            self.h[i] = 0
        self.p_no = 0
        num = '.'.join(str(x) for x in self.h[:level])
        return self.d.add_heading('%s %s' % (num, text), level=level)

    def item(self, text):
        """Пункт требования: номер подраздела + свой номер — проверяемая строка."""
        self.p_no += 1
        base = '.'.join(str(x) for x in self.h if x)
        p = self.para('%s.%d %s' % (base, self.p_no, text))
        return p

    def items(self, rows):
        for r in rows:
            self.item(r)

    def dash(self, text):
        p = self.d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.left_indent = Cm(1.25)
        p.paragraph_format.first_line_indent = Cm(-0.5)
        p.paragraph_format.space_after = Pt(1)
        p.add_run('– ' + text)

    def table(self, title, head, rows, widths=None):
        self.tables += 1
        cap = self.d.add_paragraph()
        cap.paragraph_format.space_before = Pt(6)
        cap.paragraph_format.space_after = Pt(3)
        cap.paragraph_format.keep_with_next = True
        cap.add_run('Таблица %d — %s' % (self.tables, title))
        t = self.d.add_table(rows=1, cols=len(head))
        t.style = 'Table Grid'
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for i, h in enumerate(head):
            c = t.rows[0].cells[i]
            c.text = ''
            r = c.paragraphs[0].add_run(h)
            r.bold = True
            r.font.size = Pt(10.5)
            c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        # Шапка повторяется на каждой странице.
        trPr = t.rows[0]._tr.get_or_add_trPr()
        th = OxmlElement('w:tblHeader')
        th.set(qn('w:val'), 'true')
        trPr.append(th)
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ''
                r = cells[i].paragraphs[0].add_run(str(v))
                r.font.size = Pt(10.5)
        if widths:
            for row in t.rows:
                for i, w in enumerate(widths):
                    row.cells[i].width = Cm(w)
        self.d.add_paragraph().paragraph_format.space_after = Pt(3)
        return t

    def page_break(self):
        self.d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    def toc(self):
        p = self.d.add_paragraph()
        run = p.add_run()
        for kind, text in (('begin', None), (None, 'TOC \\o "1-2" \\h \\z \\u'), ('separate', None)):
            if kind:
                el = OxmlElement('w:fldChar')
                el.set(qn('w:fldCharType'), kind)
            else:
                el = OxmlElement('w:instrText')
                el.set(qn('xml:space'), 'preserve')
                el.text = text
            run._r.append(el)
        hint = OxmlElement('w:t')
        hint.text = 'Содержание собирается при открытии документа (F9 — обновить поле).'
        run._r.append(hint)
        end = OxmlElement('w:fldChar')
        end.set(qn('w:fldCharType'), 'end')
        run._r.append(end)
        # Попросить Word обновить поля при открытии.
        settings = self.d.settings.element
        upd = OxmlElement('w:updateFields')
        upd.set(qn('w:val'), 'true')
        settings.append(upd)


