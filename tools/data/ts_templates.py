def build(module_groups):
    """module_groups — [(группа, [модули])] справочника; возвращает шаблоны."""
    known = {(g, k) for g, items in module_groups for k in items}
    out = []

    def add(name, base, modules, vtype, aliases):
        for gm in modules:
            assert gm in known, 'шаблон «%s»: нет модуля %s в справочнике' % (name, gm)
        out.append({'id': 'tpl-%d' % (len(out) + 1), 'name': name, 'category': base[0], 'base': base[1],
                    'vtype': vtype, 'modules': [{'group': g, 'kind': k} for g, k in modules],
                    'aliases': sorted(set(a.lower() for a in aliases))})

    for name, base, modules, vtype, aliases in COMPOSITE:
        add(name, base, modules, vtype, aliases)
    for group, items in module_groups:
        pick = items if group in TRUCK_GROUPS else TRUCK_ONLY.get(group, [])
        for kind in pick:
            if kind in SKIP:
                continue
            add(NAME.get(kind, kind), TRUCK, [(group, kind)], VTYPE.get(kind, VTYPE_BY_GROUP.get(group, '')),
                ALIASES.get(kind, []))
    return out
