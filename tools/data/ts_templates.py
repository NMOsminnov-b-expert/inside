def renamed(label):
    """«шаблон: Бортовой с КМУ — грузовое ТС» → новое название; остальное — как есть."""
    for old, new in RENAMED.items():
        for pre in ('шаблон: ', ''):
            if label == pre + old or label.startswith(pre + old + ' — '):
                return pre + new + label[len(pre + old):]
    return label


def build(module_groups):
    """module_groups — [(группа, [модули])] справочника; возвращает шаблоны."""
    group_of = {k: g for g, items in module_groups for k in items}
    missing = sorted(set(group_of) - set(CARRIERS))
    assert not missing, 'модули без носителей в tools/data/ts_templates.py CARRIERS: %s' % missing
    unknown = sorted(set(CARRIERS) - set(group_of))
    assert not unknown, 'в CARRIERS модули, которых нет в справочнике: %s' % unknown
    out = []

    def add(name, carrier, modules, vtype, aliases):
        kind, cat, base, _label, _ = CARRIER[carrier]
        t = {'id': 'tpl-%d' % (len(out) + 1), 'name': name, 'kind': kind, 'carrier': carrier, 'vtype': vtype,
             'order': list(CARRIER).index(carrier),
             'modules': [{'group': g, 'kind': k} for g, k in modules],
             'aliases': sorted(set(a.lower() for a in aliases))}
        if kind == 'self':
            t.update(selfGroup=cat, selfKind=base, base=base)
        else:
            t.update(category=cat, base=base)
        out.append(t)

    def label(name, carrier, many):
        return f'{name} — {CARRIER[carrier][3]}' if many else name

    for name, carrier, vtype, aliases in PLAIN:
        add(name, carrier, [], vtype, aliases)
    for name, carriers, modules, aliases in COMPOSITE:
        for c in carriers:
            kw = COMPOSITE_VTYPE.get(name, '')
            # Своя запись составного — на грузовом и прицепах; иначе — по
            # первому модулю (vtype_for): у каждого шаблона запись есть.
            vt = f'{CARRIER[c][4]}, {kw}' if kw and c in ('ГА', 'ПП', 'ПР', 'ТПР')                 else vtype_for(c, modules[0][0], modules[0][1])
            add(label(name, c, len(carriers) > 1), c, modules, vt, aliases + (GENERAL if c == 'ГА' else []))
    for group, items in module_groups:
        for kind in items:
            carriers = CARRIERS[kind]
            for c in carriers:
                add(label(NAME.get(kind, kind), c, len(carriers) > 1), c, [(group, kind)], vtype_for(c, group, kind),
                    ALIASES.get(kind, []) + (GENERAL if c == 'ГА' and group == 'Грузовые кузова' else []))
    return out
