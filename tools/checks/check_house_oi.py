# -*- coding: utf-8 -*-
"""ОИ «Жилой дом» описывается одинаково во всех типах объекта оценки.

Завести жилой дом можно в любом ОЦ — пункт есть в меню всех пяти модулей. Но
раньше признак «жилое» ставили все, а читал его только модуль «жилое здание
(дом)»: в остальных четырёх «Категория жилого строения» не появлялась, и жилой
дом терял главное поле (найдено сверкой 04.09.2026).

Второй дефект той же сверки: в производственном ОЦ назначение по умолчанию
брали от ТИПА ОЦ, поэтому жилой дом сразу получал «Производственно-складское»
вместе с блоком «Доп параметры (производственное строение)» и обязательными
высотой и наружными стенами.
"""
NAME = 'жилой дом'

ROUTES = {
    'квартира': '#/oc/apartment/oc-ap-1',
    'жилой дом': '#/oc/residential-house/oc-rh-1',
    'гражданское': '#/oc/civil/oc-cv-1',
    'производственное': '#/oc/production/oc-pr-1',
    'участок': '#/oc/land-plot/oc-lp-1',
}


def _add(t, kind):
    """Завести ОИ через меню «+ Добавить ОИ»; карточка откроется сама."""
    pg = t.page
    pg.locator('[data-dd-toggle]').first.click()
    # Меню и карточку ждём по факту: при параллельном прогоне шести браузеров
    # фиксированного ожидания не хватало, и проверка сообщала, что ОИ «не
    # заводится», хотя оно заводилось.
    t.wait_for('[data-add-oi]')
    item = pg.locator('[data-add-oi="%s"]' % kind)
    if not item.count():
        return False
    item.first.click()
    return t.wait_for('.oi-stack') and t.wait_for('.card-idx')


def run(t):
    pg = t.page

    for oc, route in ROUTES.items():
        # --- жилой дом: своё поле есть, производственных блоков нет ---
        t.open(route, wait='[data-open-oi]')
        t.wait(400)
        if not t.ck(_add(t, 'Жилой дом'), 'в %s не заводится жилой дом' % oc):
            continue

        t.ck(pg.locator('[data-rescat]').count() == 1,
             'в %s у жилого дома нет «Категории жилого строения»' % oc)

        vals = pg.eval_on_selector_all(
            '[data-rescat] option', 'els => els.map((e) => e.textContent.trim())')
        t.ck(len(vals) >= 3, 'в %s список категорий жилого строения пуст: %s' % (oc, vals))

        t.ck(pg.locator('#q-prod').count() == 0,
             'в %s жилой дом получил блок доп. параметров производственного строения' % oc)

        cc = pg.locator('[data-catclass]')
        if cc.count():
            t.ck(cc.first.input_value() != 'Производственно-складское',
                 'в %s жилому дому назначено производственно-складское' % oc)

    # --- производственное строение своё не потеряло ---
    for oc in ('производственное', 'гражданское'):
        t.open(ROUTES[oc], wait='[data-open-oi]')
        t.wait(400)
        if not t.ck(_add(t, 'Производственное строение'),
                    'в %s не заводится производственное строение' % oc):
            continue
        t.ck(pg.locator('#q-prod').count() == 1,
             'в %s у производственного строения нет блока доп. параметров' % oc)
        t.ck(pg.locator('[data-rescat]').count() == 0,
             'в %s у производственного строения показана категория жилого строения' % oc)
