# -*- coding: utf-8 -*-
"""Пополнение классификатора движимого имущества (таблица от 02.10.2026).

Что ловит сценарий:

  * новые классы таблицы (спортивный инвентарь, музыкальные инструменты,
    студийное, фото и видео) и технологический класс — из таблицы, без
    повторного класса со схемы;
  * у подгруппы без своих полей карточка показывает поля «как в файле» —
    один параметр таблицы, одно поле, подпись дословно (решение пользователя
    02.10.2026); класс выбран, а полей нет — дефект;
  * стабилизаторы — отдельный тип рядом с ИБП, со своими полями; ИБП — тип
    таблицы; передвижной асфальтобетонный завод — механизмы и оборудование;
  * прежние названия типов и подгруппы технологического класса и ИБП
    переводятся на новые, а тип без пары не теряется — уходит в «свои поля»;
  * машина для разметки дорог — модуль ТС («разметчики модулем»).
"""

NAME = 'механизмы: таблица от 02.10.2026'

TOUCHES = (
    'app/modules/mechanisms/*', 'app/modules/vehicle/data/tsCatalog.js',
    'tools/data/build_mech_classifier.py',
)

ROUTE = '#/oc/civil/oc-cv-1/oi/oi-cv1-m1'


def run(t):
    pg = t.page
    t.open(ROUTE, wait='#q-mech-unit')

    def pick(attr, value):
        pg.select_option('select[data-mu-%s]' % attr, value)
        t.wait_until("() => !!document.querySelector('#q-mech-unit')")

    # --- классы ---------------------------------------------------------------
    classes = pg.eval_on_selector_all('select[data-mu-cls] option', 'els => els.map((e) => e.value).filter(Boolean)')
    for name in ('Спортивный инвентарь', 'Музыкальные инструменты', 'Студийное/звукозаписывающее оборудование',
                 'Фото, видео и сопутствующее оборудование', 'Технологическое (производственное) оборудование'):
        t.ck(name in classes, 'нет класса «%s»: %s' % (name, classes))
    t.ck(classes.count('Технологическое (производственное) оборудование') == 1, 'технологический класс задвоился')
    t.ck('Спецтехника' not in classes, 'спецтехника попала в механизмы — это ТС')

    # --- поля «как в файле» ----------------------------------------------------
    pick('cls', 'Музыкальные инструменты')
    pick('sub', 'Клавишные инструменты')
    pick('type', 'Синтезаторы')
    labels = pg.eval_on_selector_all('#q-mech-unit [data-mu-f]', """els => els.map((e) => {
      const f = e.closest('.field'); const l = f && f.querySelector('label'); return l ? l.textContent.trim() : '';
    })""")
    for label in ('Марка (модель) и заводской (серийный) номер', 'Количество клавиш/октав',
                  'Комплектность (педали, пюпитр, стойка, чехол)'):
        t.ck(any(label in x for x in labels), 'нет поля «%s» дословно по таблице: %s' % (label, labels))
    f = pg.locator('#q-mech-unit [data-mu-f="book:количество клавиш/октав"]')
    f.fill('88')
    f.dispatch_event('change')
    pick('sub', 'Струнные инструменты')
    pick('sub', 'Клавишные инструменты')
    t.ck(pg.locator('#q-mech-unit [data-mu-f="book:количество клавиш/октав"]').input_value() == '88',
         'значение поля «как в файле» потерялось при смене подгруппы')

    # --- ИБП, стабилизаторы, асфальтобетонный завод ------------------------------
    pick('cls', 'Офисное оборудование и мебель')
    pick('sub', 'Компьютерная и оргтехника')
    types = pg.eval_on_selector_all('select[data-mu-type] option', 'els => els.map((e) => e.value)')
    t.ck('Источники бесперебойного питания (ИБП)' in types and 'Стабилизаторы напряжения' in types,
         'нет ИБП или стабилизаторов отдельными типами: %s' % types)
    pick('type', 'Стабилизаторы напряжения')
    t.ck(pg.locator('#q-mech-unit [data-mu-f="stabKind"]').count() == 1, 'у стабилизаторов нет своих полей')
    pick('cls', 'Строительное и специальное оборудование')
    pick('sub', 'Бетоносмесительное и растворосмесительное оборудование')
    types = pg.eval_on_selector_all('select[data-mu-type] option', 'els => els.map((e) => e.value)')
    t.ck('Асфальтобетонные заводы (передвижные)' in types, 'асфальтобетонного завода нет в механизмах: %s' % types)

    # --- перенос прежних названий -------------------------------------------------
    got = pg.evaluate("""async () => {
      const m = await import('./app/modules/mechanisms/form/model.js');
      const T = 'Технологическое (производственное) оборудование';
      const rec = { oi: [{ id: 'z', card: 'mech', mechanisms: [
        { id: 'a', cls: T, sub: 'Насосное, компрессорное, вентиляционное оборудование производственного назначения', type: 'Насосы', params: {}, extra: [] },
        { id: 'b', cls: T, sub: 'Технологические линии и их составные агрегаты', type: 'Производственные линии', params: {}, extra: [] },
        { id: 'c', cls: 'Офисное оборудование и мебель', sub: 'Компьютерная и оргтехника',
          type: 'Источники бесперебойного питания и стабилизаторы напряжения', params: {}, extra: [] },
      ] }] };
      m.migrateMechUnits(rec);
      return rec.oi[0].mechanisms.map((u) => [u.sub, u.type, (u.extra || []).map((x) => x.label + '=' + x.value).join(';')]);
    }""")
    t.ck(got[0][:2] == ['Насосное, компрессорное, вентиляционное оборудование', 'Насосы (центробежные, шестерённые, винтовые, погружные)'],
         'насосы не переведены на название таблицы: %s' % got[0])
    t.ck(got[1][1] == '' and got[1][2] == 'Прежний тип=Производственные линии', 'тип без пары потерян или не снят: %s' % got[1])
    t.ck(got[2][1] == 'Источники бесперебойного питания (ИБП)', 'ИБП не переведён: %s' % got[2])

    # --- разметчик — модуль ТС ----------------------------------------------------
    mods = pg.evaluate("""async () => {
      const d = await import('./app/modules/vehicle/data/tsCatalog.js');
      return JSON.stringify(d.TS_MODULE_GROUPS);
    }""")
    t.ck('Разметочное оборудование (машина для разметки дорог)' in mods, 'нет модуля «Разметочное оборудование»')
