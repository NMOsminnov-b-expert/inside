def classifier():
    js = ("Promise.all([import(process.argv[1]), import(process.argv[2])]).then(([a, b]) => "
          "console.log(JSON.stringify(a.MECH_CLASSIFIER.classes.concat(b.MECH_EXTRA_CLASSES))))")
    base = os.path.join(ROOT, 'app', 'modules', 'mechanisms', 'data')
    url = lambda f: 'file:///' + os.path.join(base, f).replace('\\', '/')
    out = subprocess.run(['node', '-e', js, url('mechClassifier.js'), url('mechFields.js')],
                         capture_output=True, check=True).stdout.decode('utf-8')
    classes = [c for c in json.loads(out) if c.get('subgroups')]
    for c in classes:
        c['draft'] = False
        for s in c['subgroups']:
            s['draft'] = False
            s['types'] = [{'name': t, 'draft': False} for t in s['types']]
    for (cn, sn), types in DRAFT_TYPES.items():
        c = next(c for c in classes if c['name'] == cn)
        s = next((s for s in c['subgroups'] if s['name'] == sn), None)
        if s is None:
            s = {'name': sn, 'draft': True, 'types': []}
            c['subgroups'].append(s)
        s['types'] += [{'name': t, 'draft': True} for t in types]
    for c in DRAFT_CLASSES:
        classes.append({'name': c['name'], 'draft': True, 'subgroups': [
            {'name': s['name'], 'draft': True, 'types': [{'name': t, 'draft': True} for t in s['types']]}
            for s in c['subgroups']]})
    return classes


