def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--opisi', default=r'C:\Нормализованные описи')
    ap.add_argument('--out')
    args = ap.parse_args()
    out = args.out or os.path.join(args.opisi, 'граф')
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

    classes = classifier()
    invs, rows, dropped = inventories(args.opisi)
    print('строк взято %d, не взято: %s' % (len(rows), dict(dropped)))

    # Типы и их векторы («класс / подгруппа / тип»).
    types = []
    for c in classes:
        for s in c['subgroups']:
            for t in s['types']:
                types.append({'cls': c['name'], 'sub': s['name'], 'name': t['name'], 'draft': t['draft'] or s['draft'] or c['draft']})
    emb = Embedder(os.path.join(out, '.cache'))
    tv = emb(['%s / %s / %s' % (t['cls'], t['sub'], t['name']) for t in types])

    # Наименование + тип описи → тип: сначала однозначные признаки, затем по смыслу.
    by_name = {t['name']: i for i, t in enumerate(types)}
    for rx, tn in KEYWORDS:
        if tn is not None and tn not in by_name:
            sys.exit('в KEYWORDS тип не из дерева: ' + tn)
    pairs = sorted({(key(r['name']), r['otype']) for r in rows})
    names = {p[0]: next(r['name'] for r in rows if key(r['name']) == p[0]) for p in pairs}
    best, rule_hit = {}, {}
    for nk, ot in pairs:
        for rx, tn in KEYWORDS:
            if re.search(rx, nk):
                rule_hit[(nk, ot)] = by_name[tn] if tn else -1
                break
    clean = lambda n: re.sub(r'\s+', ' ', re.sub('|'.join(NOISE), ' ', n, flags=re.I)).strip() or n
    rest = [p for p in pairs if p not in rule_hit]
    nv = dict(zip([p[0] for p in rest], emb([QUERY + clean(names[p[0]]) for p in rest])))
    for p, i in rule_hit.items():
        best[p] = (i, 1.0, 1.0) if i >= 0 else (-1, 0.0, 0.0)
    for nk, ot in rest:
        allowed = OPIS_TYPE_CLASSES.get(ot)
        cand = [(dot(nv[nk], tv[i]), i) for i, t in enumerate(types) if not allowed or t['cls'] in allowed]
        cand.sort(reverse=True)
        (s1, i1), s2 = cand[0], (cand[1][0] if len(cand) > 1 else 0)
        best[(nk, ot)] = (i1, s1, s1 - s2)
    for r in rows:
        i, s, m = best[(key(r['name']), r['otype'])]
        r['type'], r['score'], r['margin'] = (i if i >= 0 and s >= MIN_SCORE and m >= MIN_MARGIN else None), s, m
    # Сопоставления — для проверки глазами и подбора порога.
    json.dump([{'name': names[nk], 'otype': ot, 'type': ('%s / %s' % (types[i]['sub'], types[i]['name'])) if i >= 0 else '—',
                'how': 'правило' if (nk, ot) in rule_hit else 'по смыслу', 'score': round(s, 3),
                'margin': round(m, 3)} for (nk, ot), (i, s, m) in best.items()],
              open(os.path.join(out, '.cache', 'assign.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)

    write(out, classes, types, invs, rows, dropped)


