class Embedder:
    def __init__(self, cache_dir):
        os.makedirs(cache_dir, exist_ok=True)
        self.path = os.path.join(cache_dir, 'emb-%s.json' % slug(MODEL))
        self.cache = json.load(open(self.path, encoding='utf-8')) if os.path.exists(self.path) else {}

    def __call__(self, texts):
        need = [t for t in dict.fromkeys(texts) if t not in self.cache]
        for i in range(0, len(need), 32):
            part = need[i:i + 32]
            body = json.dumps({'model': MODEL, 'input': part, 'options': {'num_ctx': 1024, 'num_thread': 3}}).encode('utf-8')
            req = urllib.request.Request(OLLAMA, body, {'Content-Type': 'application/json'})
            opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
            vecs = json.load(opener.open(req, timeout=600))['embeddings']
            for t, v in zip(part, vecs):
                n = math.sqrt(sum(x * x for x in v)) or 1
                self.cache[t] = [x / n for x in v]
            print('  векторов %d из %d' % (min(i + 32, len(need)), len(need)), flush=True)
        if need:
            json.dump(self.cache, open(self.path, 'w', encoding='utf-8'))
        return [self.cache[t] for t in texts]


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


