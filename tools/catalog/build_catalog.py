def review_fixes(opisi):
    """Жёлтые и похожие строки из книги перепроверки → (опись, строка): статус."""
    path = os.path.join(opisi, 'Перепроверка цветных строк.xlsx')
    fixes = {}
    if not os.path.exists(path):
        return fixes
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=True)
    for name in ('Жёлтые', 'Похожие без цвета'):
        if name not in wb.sheetnames:
            continue
        it = wb[name].iter_rows(values_only=True)
        head = next(it)
        for r in it:
            d = dict(zip(head, r))
            if d.get('Предлагаемый статус') in TAKE:
                fixes[(d['Опись'], d['Строка'])] = d['Предлагаемый статус']
    return fixes


def inventories(opisi):
    import openpyxl
    fixes = review_fixes(opisi)
    invs, rows, dropped = [], [], collections.Counter()
    for path in sorted(glob.glob(os.path.join(opisi, '*опись.xlsx'))):
        name = os.path.basename(path).replace(' — опись.xlsx', '')
        wb = openpyxl.load_workbook(path, read_only=True)
        summary = [norm(x) for r in list(wb['Сводка'].iter_rows(values_only=True))[:3] for x in r if x]
        inv = {'name': name, 'summary': summary, 'taken': 0, 'by_status': collections.Counter()}
        invs.append(inv)
        it = wb['Опись'].iter_rows(values_only=True)
        head = next(it)
        for n, r in enumerate(it, start=2):
            d = dict(zip(head, r))
            status = fixes.get((name, n), d.get('Статус'))
            inv['by_status'][d.get('Статус')] += 1
            if status not in TAKE:
                continue
            if 'выбыло' in str(d.get('Причина') or '').lower():
                dropped['выбывшие'] += 1
                continue
            low = key(d.get('Основное средство'))
            hit = next((g for g, p in DISPUTED if re.search(p, low)), None)
            if not hit and re.search(VIDEO_WATCH, low):
                hit = 'видеонаблюдение'
            if hit:
                dropped['спорная группа: ' + hit] += 1
                continue
            ot = norm(d.get('Тип объекта (определён)'))
            if OPIS_TYPE_CLASSES.get(ot) == 'skip':
                dropped['не оборудование: ' + ot] += 1
                continue
            qty = d.get('Количество')
            rows.append({'inv': name, 'row': n, 'name': norm(d.get('Основное средство')), 'model': norm(d.get('Модель средства')),
                         'qty': int(qty) if isinstance(qty, (int, float)) and qty > 0 else 1,
                         'status': status, 'otype': ot})
            inv['taken'] += 1
    return invs, rows, dropped


